/// The dialect a surveyed member was observed with, or `None` for a member
/// no rule covers (whatever its extension). `member` is `None` for a loose
/// file, whose installation path is then `container`.
pub fn dialect_for_member(container: &str, member: Option<&str>) -> Option<TextDialect> {
    TEXT_DIALECT_INVENTORY
        .iter()
        .find(|record| {
            record
                .members
                .iter()
                .any(|rule| rule.matches(container, member))
        })
        .map(|record| record.dialect)
}
