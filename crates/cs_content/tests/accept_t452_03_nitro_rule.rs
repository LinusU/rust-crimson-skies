fn image() -> Vec<u8> {
    let path = std::env::var_os("CS_ENGINE_IMAGE").expect(
        "CS_ENGINE_IMAGE is not set: this measurement needs the owner-supplied decrypted \
         executable",
    );
    std::fs::read(&path).expect("the engine image reads")
}

#[test]
#[ignore = "requires CS_ENGINE_IMAGE"]
fn accept_t452_03_image_pins_the_nitro_rule() {
    let image = image();
    for (address, bytes, meaning) in PINS {
        let offset = usize::try_from(address - IMAGE_BASE).expect("offset");
        assert_eq!(
            &image[offset..offset + bytes.len()],
            bytes,
            "0x{address:x} no longer carries: {meaning}"
        );
    }
    // The three float constants the rule compares against.
    for (address, value) in [
        (0x60_34d8_u64, 0.05_f32),
        (0x60_80a8, 0.99),
        (0x60_8b9c, 1.25),
    ] {
        let offset = usize::try_from(address - IMAGE_BASE).expect("offset");
        let got = f32::from_le_bytes(image[offset..offset + 4].try_into().expect("4 bytes"));
        assert_eq!(got, value, "0x{address:x}");
    }
}

#[test]
fn accept_t452_03_record_carries_the_pinned_constants() {
    let n = ORIGINAL_NITRO;
    assert_eq!(f32::from_bits(0x41f0_0000), n.capacity as f32);
    assert_eq!(f32::from_bits(0x4080_0000), n.consumption_per_dt as f32);
    assert_eq!(f32::from_bits(0x3f80_0000), n.recovery_per_dt as f32);
    assert_eq!(f32::from_bits(0x3f7d_70a4), n.start_min_fraction as f32);
    assert_eq!(f32::from_bits(0x3d4c_cccd), n.stop_below_fraction as f32);
    assert_eq!(f32::from_bits(0x3fe6_6666), n.running_engine_value as f32);
    assert_eq!(f32::from_bits(0x3f4c_cccd), n.running_result_factor as f32);
}

#[test]
fn accept_t452_03_charge_recovers_even_while_running() {
    let n = ORIGINAL_NITRO;
    // Idle: +1 per delta up to the capacity.
    assert_eq!(n.step_charge(10.0, false, 2.0), 12.0);
    assert_eq!(n.step_charge(29.5, false, 2.0), 30.0);
    // Running: -4 and +1 per delta, a net -3.
    assert_eq!(n.step_charge(30.0, true, 1.0), 27.0);
    // Never below zero.
    assert_eq!(n.step_charge(1.0, true, 5.0), 0.0);
}

#[test]
fn accept_t452_03_a_full_burn_runs_to_five_percent_and_cannot_restart_until_full() {
    let n = ORIGINAL_NITRO;
    let (mut charge, mut running) = (n.capacity, false);
    assert_eq!(n.player_command(charge, running, true), Some(true));
    running = true;
    let mut steps = 0;
    // Releasing the control (false) never cuts it; only the charge does.
    loop {
        charge = n.step_charge(charge, running, 1.0);
        steps += 1;
        if n.player_command(charge, running, false) == Some(false) {
            break;
        }
        assert!(steps < 100, "the burn never ended");
    }
    // 30 -> 27 -> ... -> 3 (nine steps, still above 1.5) -> 0 on the tenth.
    assert_eq!(steps, 10);
    assert_eq!(charge, 0.0);
    running = false;
    // Idle again: no start below 99% even with the control held.
    assert_eq!(n.player_command(29.6, running, true), None);
    assert_eq!(n.player_command(29.7, running, true), Some(true));
    // A running booster below 99% is held, not restarted by the control.
    assert_eq!(n.player_command(20.0, true, false), Some(true));
    // Below 5% it is cut whatever the control says.
    assert_eq!(n.player_command(1.4, true, true), Some(false));
    assert_eq!(n.player_command(1.4, false, true), Some(false));
}
