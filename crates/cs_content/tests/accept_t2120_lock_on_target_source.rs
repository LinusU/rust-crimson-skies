//! Task #2120 against the owner's engine image: how the guided (`LOCK_ON`)
//! weapon records obtain a projectile target when no store of `[reg+0x70]`
//! assigns one.
//!
//! Task test prefix: `accept_t2120_`. Findings:
//! `docs/findings/2026-10-25-t2120-lock-on-target-source.md`.
//!
//! The answer is a launch-time hand-over the byte scan of #2116 could not see:
//! the launch `0x5aef40` copies three dwords from a pending triple (globals
//! `0xa1d7cc` / `0xa1d7d0`, set by the setter `0x5ac0a0`) into the projectile's
