fn image() -> Vec<u8> {
    let path = std::env::var_os("CS_ENGINE_IMAGE").expect(
        "CS_ENGINE_IMAGE is not set: this measurement needs the owner-supplied decrypted \
         executable",
    );
    std::fs::read(&path).expect("the engine image reads")
}

fn at(image: &[u8], address: u64, len: usize) -> &[u8] {
    let offset = usize::try_from(address - IMAGE_BASE).expect("offset");
    &image[offset..offset + len]
}

/// Every virtual address of an `e8 rel32` whose target is `target`.
fn direct_calls(text: &[u8], target: u64) -> Vec<u64> {
    let mut found = Vec::new();
    for i in 0..text.len().saturating_sub(4) {
        if text[i] != 0xe8 {
            continue;
        }
        let rel = i32::from_le_bytes([text[i + 1], text[i + 2], text[i + 3], text[i + 4]]);
        let address = TEXT_START + i as u64;
        if address.wrapping_add(5).wrapping_add_signed(i64::from(rel)) == target {
            found.push(address);
        }
    }
    found
}

#[test]
#[ignore = "requires CS_ENGINE_IMAGE"]
fn accept_t2120_image_pins_the_launch_time_target_hand_over() {
    let image = image();
    for (address, bytes, meaning) in IMAGE_PINS {
        assert_eq!(
            at(&image, address, bytes.len()),
            bytes,
            "0x{address:x} no longer carries: {meaning}"
        );
    }

    // The setter has exactly five callers and its address is never data.
    let text = at(&image, TEXT_START, TEXT_LEN);
    assert_eq!(direct_calls(text, SETTER), SETTER_CALLERS.to_vec());
    let absolute = (SETTER as u32).to_le_bytes();
    let as_data = image
        .windows(4)
        .filter(|window| *window == absolute)
        .count();
    assert_eq!(as_data, 0, "the setter's address is stored as data");

    // The count word the player and gun-controller callers pass is the
    // constant 1 (`.rdata`, file offset equals address minus the base).
    assert_eq!(at(&image, 0x62_b11c, 4), 1_i32.to_le_bytes());

    // The pending globals are written only by the setter, the two resets
    // (0x5ad522, 0x5ae91f) and the launch's own clear.
    let mut writers = Vec::new();
    for global in [0xa1_d7cc_u32, 0xa1_d7d0] {
        // `mov [abs32], reg` is `89 /r` with mod=00 r/m=101 (opcode, modrm,
        // address) or, from eax, the short form `a3 moffs32`.
        for i in 0..text.len().saturating_sub(6) {
            let long = text[i] == 0x89
                && text[i + 1] & 0xc7 == 0x05
                && text[i + 2..i + 6] == global.to_le_bytes();
            let short = text[i] == 0xa3 && text[i + 1..i + 5] == global.to_le_bytes();
            if long || short {
                writers.push(TEXT_START + i as u64);
            }
        }
    }
    writers.sort_unstable();
    assert_eq!(
        writers,
        [
            0x5a_c0a8, 0x5a_c0ad, 0x5a_d522, 0x5a_d527, 0x5a_e91f, 0x5a_e925, 0x5a_f65e
        ]
    );
}
