//! Evidence-report harness for task #2121 (`docs/contracts/CLI-EVIDENCE.md`,
//! `schemas/evidence.schema.json`). Not named `accept_t2121_*`: it is not part of
//! the acceptance suite and fails loudly when its inputs are missing.
//!
//! 1. `cargo test --workspace --locked -- accept_t2121_ --include-ignored 2>&1 |
//!    tee private/evidence/T2121/cargo-test.log` (note the exit status)
//! 2. ```sh
//!    CS_EVIDENCE_DIR=private/evidence/T2121 \
//!    CS_CANDIDATE_TREE=$(git rev-parse 'HEAD^{tree}') \
//!    CS_EVIDENCE_ARGV="cargo test --workspace --locked -- accept_t2121_ --include-ignored" \
//!    CS_EVIDENCE_EXIT_CODE=<status> CS_EVIDENCE_REVIEWER=<identity> \
//!      cargo test --locked -p cs_content --test cs_content_tests evidence_report_t2121 -- --ignored
//!    ```
//! 3. `python3 tools/validate_evidence.py private/evidence/T2121/acceptance.json
//!    --artifact-root private/evidence/T2121 --require-pass`
//! 4. Commit a copy as `docs/findings/evidence/T2121.json`.
//!
//! `target-values.json` is a second record: the executable's SHA-256, the
//! resolution of the unknown task #2121 left open and the remaining
//! limitations. Identifiers, numbers and digests only; no original display
//! text.
//!
//! **On `unknowns`.** `--require-pass` rejects a nonempty `unknowns` list, and
//! this task has no unresolved issue inside its own assertions. The original
//! facts it leaves unmeasured are fidelity limitations, named with their
//! affected content in `LIMITATIONS` below, in `target-values.json` (a hashed
//! artifact) and in `docs/findings/2026-10-25-t2121-beeper-target-values.md`,
//! so none is removed from machine-readable evidence to turn a validator green.
//! The claim is `implemented`; `retail` is read access, not an original run.

