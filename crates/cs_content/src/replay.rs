/// Schema version of a [`ReplayRecord`]. A different major is unreadable; a
/// newer minor of the same major is readable and its unknown lines are
/// preserved in [`ReplayRecord::extra`].
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct ReplayVersion {
    pub major: u16,
    pub minor: u16,
}

impl ReplayVersion {
    /// The version this build writes.
    pub const CURRENT: Self = Self { major: 1, minor: 0 };

    /// Whether this build can read a document of this version.
    pub const fn is_readable(self) -> bool {
        self.major == Self::CURRENT.major
    }
}

impl fmt::Display for ReplayVersion {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}.{}", self.major, self.minor)
    }
}

/// A git object id: 40 or 64 lowercase hex characters.
///
/// Both widths are accepted because the candidate tree hash
/// (`CS_CANDIDATE_TREE`) is a git object id, whose algorithm is the
/// repository's choice, not this module's. Uppercase is refused so two
/// spellings of one build can never compare unequal.
#[derive(Clone, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct BuildId(String);

impl BuildId {
    /// Validates and wraps a git object id.
    ///
    /// # Errors
    ///
    /// [`ReplayError::TooLong`] above [`MAX_LABEL_BYTES`], and
    /// [`ReplayError::Syntax`] for a width that is neither 40 nor 64 or a
    /// character that is not a lowercase hex digit.
    pub fn new(text: &str) -> Result<Self, ReplayError> {
        if text.len() > MAX_LABEL_BYTES {
            return Err(ReplayError::TooLong {
                field: "build id",
                len: text.len(),
                max: MAX_LABEL_BYTES,
            });
        }
        if text.len() != 40 && text.len() != 64 {
            return Err(ReplayError::Syntax {
                field: "build id",
                reason: "expected 40 or 64 hex digits",
            });
        }
        if !text.bytes().all(|b| matches!(b, b'0'..=b'9' | b'a'..=b'f')) {
            return Err(ReplayError::Syntax {
                field: "build id",
                reason: "expected lowercase hex digits",
            });
        }
        Ok(Self(text.to_owned()))
    }

    /// The id as a string slice.
    pub fn as_str(&self) -> &str {
        &self.0
    }
}

impl fmt::Display for BuildId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.0)
    }
}

/// The operating system and architecture a build ran on.
///
/// A replay recorded on one platform is not a replay of another platform
/// (F59 non-negotiable 1), and the two axes are kept apart so the refusal
/// says which one moved.
#[derive(Clone, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct PlatformTag {
    os: String,
    arch: String,
}

impl PlatformTag {
    /// Validates and wraps a platform tag.
    ///
    /// # Errors
    ///
    /// [`ReplayError::Blank`] for an empty axis, [`ReplayError::TooLong`]
    /// above [`MAX_LABEL_BYTES`], and [`ReplayError::Syntax`] for a character
    /// outside ASCII alphanumerics, `-`, `_` and `.`.
    pub fn new(os: &str, arch: &str) -> Result<Self, ReplayError> {
        Ok(Self {
            os: check_label("platform os", os)?,
            arch: check_label("platform arch", arch)?,
        })
    }

    /// The operating system label.
    pub fn os(&self) -> &str {
        &self.os
    }

    /// The architecture label.
    pub fn arch(&self) -> &str {
        &self.arch
    }

    /// Whether both axes of two tags are equal.
    pub fn same_as(&self, other: &Self) -> bool {
        self.os == other.os && self.arch == other.arch
    }
}

impl fmt::Display for PlatformTag {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}-{}", self.os, self.arch)
    }
}

/// Checks a bounded ASCII label: non-empty, no whitespace, and only the
/// characters an id, a platform tag or a claim name may use.
fn check_label(field: &'static str, text: &str) -> Result<String, ReplayError> {
    if text.trim().is_empty() {
        return Err(ReplayError::Blank { field });
    }
    if text.len() > MAX_LABEL_BYTES {
        return Err(ReplayError::TooLong {
            field,
            len: text.len(),
            max: MAX_LABEL_BYTES,
        });
    }
    for ch in text.chars() {
        if !ch.is_ascii_alphanumeric() && !matches!(ch, '.' | '_' | '-' | ':' | '/') {
            return Err(ReplayError::Syntax {
                field,
                reason: "expected ASCII alphanumerics, '.', '_', '-', ':' or '/'",
            });
        }
    }
    Ok(text.to_owned())
}

/// Checks a free-text value: non-empty, within its byte bound, and single-line
/// so the line format stays unambiguous.
fn check_text(field: &'static str, text: &str) -> Result<(), ReplayError> {
    if text.trim().is_empty() {
        return Err(ReplayError::Blank { field });
    }
    if text.len() > MAX_VALUE_BYTES {
        return Err(ReplayError::TooLong {
            field,
            len: text.len(),
            max: MAX_VALUE_BYTES,
        });
    }
    if text.contains(['\n', '\r']) {
        return Err(ReplayError::Syntax {
            field,
            reason: "a value must be a single line",
        });
    }
    Ok(())
}

/// What a build is: which candidate tree it came from, which three digests
/// describe it, which toolchain produced it and which platform it ran on.
///
/// The engine, content and rules digests are three fields rather than one
/// because they change for different reasons and a report has to be able to
/// say which: a content asset changing (AC02) invalidates a replay, and so
/// does a rules-table edit, and so does a rebuild of the engine — but a
/// reviewer reading the refusal needs to know which one moved.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct BuildFingerprint {
    /// The candidate tree hash (`CS_CANDIDATE_TREE`).
    pub tree: BuildId,
    /// Digest of the engine sources the build was made from.
    pub engine: ContentHash,
    /// Digest of the canonical content the run loaded. A synthetic run's
    /// fixture content has a digest too; it is simply not a retail one.
    pub content: ContentHash,
    /// Digest of the declared rules and tuning tables in force.
    pub rules: ContentHash,
    /// Engine and toolchain versions, e.g. `rustc 1.98.0; bevy 0.19`.
    pub toolchain: String,
    /// The platform the build ran on.
    pub platform: PlatformTag,
}

impl BuildFingerprint {
    /// Checks the bounds a record's own fields must satisfy.
    ///
    /// # Errors
    ///
    /// [`ReplayError::Blank`] or [`ReplayError::TooLong`] for an empty or
    /// oversized toolchain string.
    pub fn validate(&self) -> Result<(), ReplayError> {
        check_text("toolchain", &self.toolchain)
    }
}

/// The state a run started from: a label for it and the digest measured over
/// it.
///
/// The digest is supplied by the runtime that measured a real initial state
/// (F59-B). A replay that carries no initial-state digest cannot claim to
/// reproduce a run, so the field is required rather than optional.
///
/// The label is free text rather than an id grammar: it names *what* was
/// hashed, including the `@tick0`-style anchor a producer needs to say the
/// state was measured before the first tick ran.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct InitialState {
    /// What was hashed, e.g. `synthetic.falling-box@tick0`.
    pub label: String,
    /// The digest measured over that state.
    pub digest: ContentHash,
}

impl InitialState {
    /// Validates and wraps an initial-state record.
    ///
    /// # Errors
    ///
    /// [`ReplayError::Blank`] for an empty label, [`ReplayError::TooLong`] for
    /// a label over [`MAX_VALUE_BYTES`], and [`ReplayError::Syntax`] for a
    /// multi-line one.
    pub fn new(label: &str, digest: ContentHash) -> Result<Self, ReplayError> {
        check_text("initial state label", label)?;
        Ok(Self {
            label: label.to_owned(),
            digest,
        })
    }
}

