/// Feeds one length-prefixed field, so no two field sequences can collide on a
/// shared byte boundary. Same rule as `cs_assets::cache::key`.
fn put_field(hasher: &mut Sha256, bytes: &[u8]) {
    hasher.update(&(bytes.len() as u64).to_le_bytes());
    hasher.update(bytes);
}

fn put_text(hasher: &mut Sha256, text: &str) {
    put_field(hasher, text.as_bytes());
}

fn put_u64(hasher: &mut Sha256, value: u64) {
    hasher.update(&value.to_le_bytes());
}

fn put_hash(hasher: &mut Sha256, hash: ContentHash) {
    put_field(hasher, hash.as_bytes());
}

