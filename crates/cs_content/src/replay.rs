/// The authored decisions a replay has to pin for the run to be the same run.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum ChoiceSlot {
    /// The airframe the session launched.
    Airframe,
    /// The difficulty profile in force.
    Difficulty,
    /// The weapon and equipment loadout.
    Loadout,
    /// Which assists were enabled.
    Assists,
    /// The mission the session ran.
    Mission,
    /// Which rules/tuning set was in force.
    Ruleset,
}

impl ChoiceSlot {
    /// Every slot, in a stable order.
    pub const ALL: &'static [ChoiceSlot] = &[
        Self::Airframe,
        Self::Difficulty,
        Self::Loadout,
        Self::Assists,
        Self::Mission,
        Self::Ruleset,
    ];

    /// The stable label used in the document form.
    pub const fn label(self) -> &'static str {
        match self {
            Self::Airframe => "airframe",
            Self::Difficulty => "difficulty",
            Self::Loadout => "loadout",
            Self::Assists => "assists",
            Self::Mission => "mission",
            Self::Ruleset => "ruleset",
        }
    }

    /// Looks a slot up by its label; `None` for an unknown slot.
    pub fn from_label(label: &str) -> Option<Self> {
        Self::ALL.iter().copied().find(|slot| slot.label() == label)
    }
}

impl fmt::Display for ChoiceSlot {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.label())
    }
}

/// One pinned authored choice and the provenance of its value.
///
/// The provenance is required, not decorative: a replay that silently assumed
/// the default difficulty or loadout would replay a run nobody played. The
/// value is text because the slots are heterogeneous (a loadout is a set, an
/// assist list is a set of flags); what the value *means* is the runtime's
/// business, and the compatibility signature compares it exactly.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct AuthoredChoice {
    pub slot: ChoiceSlot,
    pub value: String,
    /// Where the value came from and how strong that evidence is.
    pub provenance: Provenance,
}

/// The pinned authored choices of a replay, in canonical slot order.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct AuthoredChoices(Vec<AuthoredChoice>);

impl AuthoredChoices {
    /// Sorts the choices into canonical order, refusing a repeated slot.
    ///
    /// # Errors
    ///
    /// [`ReplayError::Duplicate`] for a slot held twice,
    /// [`ReplayError::TooManyEntries`] above [`MAX_CHOICES`] and
    /// [`ReplayError::Blank`] for an empty value.
    pub fn new(mut choices: Vec<AuthoredChoice>) -> Result<Self, ReplayError> {
        if choices.len() > MAX_CHOICES {
            return Err(ReplayError::TooManyEntries {
                what: "authored choices",
                max: MAX_CHOICES,
            });
        }
        for choice in &choices {
            check_text("choice value", &choice.value)?;
        }
        choices.sort_by_key(|choice| choice.slot);
        for pair in choices.windows(2) {
            if pair[0].slot == pair[1].slot {
                return Err(ReplayError::Duplicate {
                    what: "authored choice",
                    key: pair[0].slot.label().to_owned(),
                });
            }
        }
        Ok(Self(choices))
    }

    /// An empty choice set.
    #[must_use]
    pub fn none() -> Self {
        Self(Vec::new())
    }

    /// The choices, in canonical slot order.
    pub fn choices(&self) -> &[AuthoredChoice] {
        &self.0
    }

    /// The value pinned for one slot.
    pub fn get(&self, slot: ChoiceSlot) -> Option<&str> {
        self.0
            .iter()
            .find(|choice| choice.slot == slot)
            .map(|choice| choice.value.as_str())
    }

    /// Whether no choice is pinned.
    pub fn is_empty(&self) -> bool {
        self.0.is_empty()
    }

    /// How many choices are pinned.
    pub fn len(&self) -> usize {
        self.0.len()
    }

    /// The canonical text form: `slot=value` per choice, sorted, with the
    /// provenance class, so two records that pin the same values with a
    /// stronger provenance are *not* silently equal.
    pub fn canonical(&self) -> String {
        let mut text = String::new();
        for choice in &self.0 {
            text.push_str(choice.slot.label());
            text.push('=');
            text.push_str(choice.provenance.class.label());
            text.push(':');
            text.push_str(choice.provenance.claim_id.as_str());
            text.push(':');
            text.push_str(&choice.value);
            text.push('\n');
        }
        text
    }
}

