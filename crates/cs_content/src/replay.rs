/// The claim id the synthetic fixtures below carry as their provenance. It is
/// a design claim, not an observation of the original game.
pub const SYNTHETIC_FIXTURE_CLAIM: &str = "f59.a.synthetic-fixture";

/// The root seed the synthetic replay fixture uses.
pub const SYNTHETIC_REPLAY_SEED: u64 = 20_260_901;

/// The synthetic body stream's domain constant
/// (`cs_types::random::SYNTHETIC_BODY_DOMAIN`), named here so the fixture's
/// stream list matches what a seeded synthetic run really draws.
const SYNTHETIC_BODY_DOMAIN: u64 = cs_types::random::SYNTHETIC_BODY_DOMAIN;

/// A synthetic per-tick state digest: the digest of a **labelled fixture
/// description**, not a simulation result.
///
/// It exists so the envelope, its chain, the comparison and the document form
/// can be exercised without a runtime. No code may read it as measured state:
/// a real state hash comes from a running session (F59-B) through
/// [`StateEnvelope::push`].
fn synthetic_state_digest(tick: Tick, frame: &InputFrame) -> ContentHash {
    let mut hasher = Sha256::new();
    hasher.update(ENVELOPE_CHAIN_DOMAIN);
    put_text(&mut hasher, "cs.f59.synthetic.state.v1");
    put_u64(&mut hasher, tick.0);
    put_text(&mut hasher, &encode_frame(frame));
    hasher.finalize()
}

/// The minimal synthetic replay fixture: four recorded input ticks, a
/// promised state hash for each, and one pinned authored choice per slot.
///
/// Every value is newly authored project design. It is a development fixture
/// for this module's own checks; it is not a recording of a mission, and it
/// certifies nothing about the original game.
#[must_use]
pub fn synthetic_replay_record() -> ReplayRecord {
    let mut stream = CommandStream::new();
    let mut promised = StateEnvelope::new();
    // Sparse ticks on purpose: a run that recorded nothing for a few ticks has
    // no records there, and a replay reproduces the pause because there is
    // nothing to replay.
    for (index, tick) in [0u64, 1, 5, 9].into_iter().enumerate() {
        let mut frame = InputFrame::new(Tick(tick));
        frame.set_axis(
            AxisValue::from_quantized(FlightCommand::Pitch, (index as i16 + 1) * 1024)
                .expect("pitch is a continuous axis"),
        );
        if index == 2 {
            frame.push_edge(Action::Flight(FlightCommand::FirePrimary));
        }
        if index == 3 {
            frame.push_edge(Action::Ui(cs_types::input::UiAction::Pause));
        }
        promised
            .push(Tick(tick), synthetic_state_digest(Tick(tick), &frame))
            .expect("the fixture's ticks strictly increase");
        stream
            .record_tick(frame)
            .expect("the fixture's ticks strictly increase");
    }

    ReplayRecord {
        schema: ReplayVersion::CURRENT,
        subject: ContentId::from_source(
            cs_types::content::ContentKind::Mission,
            "synthetic.replay",
        )
        .expect("the fixture's content id is valid"),
        fingerprint: BuildFingerprint {
            tree: BuildId::new("1111111111111111111111111111111111111111")
                .expect("the fixture's build id is 40 hex digits"),
            engine: cs_assets::install::sha256(b"cs.f59.synthetic.engine"),
            content: cs_assets::install::sha256(b"cs.f59.synthetic.content"),
            rules: cs_assets::install::sha256(b"cs.f59.synthetic.rules"),
            toolchain: "synthetic; rustc 0.0.0".to_owned(),
            platform: PlatformTag::new("synthetic", "none")
                .expect("the fixture's platform tag is valid"),
        },
        initial_state: InitialState::new(
            "synthetic.replay@tick0",
            cs_assets::install::sha256(b"cs.f59.synthetic.initial"),
        )
        .expect("the fixture's initial state label is valid"),
        stream,
        seeds: ReplaySeeds::derive(
            SYNTHETIC_REPLAY_SEED,
            &[(SYNTHETIC_BODY_DOMAIN, "synthetic_body")],
        )
        .expect("the fixture's seed list is valid"),
        tick_rate: 120,
        first_tick: Tick(0),
        last_tick: Tick(9),
        choices: AuthoredChoices::new(vec![AuthoredChoice {
            slot: ChoiceSlot::Mission,
            value: "synthetic.replay".to_owned(),
            provenance: Provenance::designed(
                ClaimId::new(SYNTHETIC_FIXTURE_CLAIM).expect("the fixture's claim id is valid"),
            ),
        }])
        .expect("the fixture's choices are valid"),
        promised,
        overrides: OverrideLog::ordinary_play(),
        extra: Vec::new(),
    }
}

