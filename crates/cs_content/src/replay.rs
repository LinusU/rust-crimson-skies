/// Why a replay, capture or evidence record was refused.
///
/// Every variant names the field or entry that broke the rule. Nothing is
/// repaired into a plausible value: a record this module accepts is a record
/// whose fields can be believed.
///
/// `PartialEq` and not `Eq` because [`ReplayError::Camera`] wraps a
/// [`CaptureError`], which carries a rejected float.
#[derive(Clone, Debug, PartialEq)]
pub enum ReplayError {
    /// A required text field was empty or only whitespace.
    Blank {
        /// The offending field.
        field: &'static str,
    },
    /// A field exceeded its declared byte bound.
    TooLong {
        /// The offending field.
        field: &'static str,
        /// Its measured length in bytes.
        len: usize,
        /// The bound it exceeded.
        max: usize,
    },
    /// A field's characters are outside the grammar its kind allows.
    Syntax {
        /// The offending field.
        field: &'static str,
        /// What was wrong with it.
        reason: &'static str,
    },
    /// A tick rate of zero was declared; there would be no fixed dt.
    ZeroTickRate,
    /// A run's last tick is before its first tick.
    InvertedTickRange {
        /// The declared first tick.
        first: Tick,
        /// The declared last tick.
        last: Tick,
    },
    /// A recorded input tick or a promised state hash lies outside the run's
    /// declared tick range.
    OutsideTickRange {
        /// What kind of entry was outside.
        what: &'static str,
        /// The offending tick.
        tick: Tick,
        /// The declared first tick.
        first: Tick,
        /// The declared last tick.
        last: Tick,
    },
    /// Two entries claimed the same key, so a set of them is ambiguous.
    Duplicate {
        /// What the entries are.
        what: &'static str,
        /// The duplicated key.
        key: String,
    },
    /// A bounded list held more entries than the bound allows.
    TooManyEntries {
        /// What the entries are.
        what: &'static str,
        /// The bound.
        max: usize,
    },
    /// The promised state envelope broke its own ordering or bounds.
    Envelope(EnvelopeError),
    /// A camera pose was not finite or a field of view was not a real angle.
    Camera(CaptureError),
    /// The record declares a schema major this build cannot read.
    UnreadableSchema {
        /// The declared major.
        major: u16,
    },
}

impl fmt::Display for ReplayError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Blank { field } => write!(f, "{field} must not be empty"),
            Self::TooLong { field, len, max } => {
                write!(f, "{field} is {len} bytes, over the bound of {max}")
            }
            Self::Syntax { field, reason } => write!(f, "{field} is invalid: {reason}"),
            Self::ZeroTickRate => write!(f, "a replay must declare a nonzero tick rate"),
            Self::InvertedTickRange { first, last } => write!(
                f,
                "the run's last tick {} is before its first tick {}",
                last.0, first.0
            ),
            Self::OutsideTickRange {
                what,
                tick,
                first,
                last,
            } => write!(
                f,
                "{what} at tick {} is outside the declared range {}..={}",
                tick.0, first.0, last.0
            ),
            Self::Duplicate { what, key } => write!(f, "{what} is declared twice: {key}"),
            Self::TooManyEntries { what, max } => {
                write!(f, "a record may hold at most {max} {what}")
            }
            Self::Envelope(error) => write!(f, "state envelope: {error}"),
            Self::Camera(error) => write!(f, "capture camera: {error}"),
            Self::UnreadableSchema { major } => {
                write!(
                    f,
                    "replay schema major {major} is not readable by this build"
                )
            }
        }
    }
}

impl std::error::Error for ReplayError {}

impl From<EnvelopeError> for ReplayError {
    fn from(error: EnvelopeError) -> Self {
        Self::Envelope(error)
    }
}

impl From<CaptureError> for ReplayError {
    fn from(error: CaptureError) -> Self {
        Self::Camera(error)
    }
}

/// Why a promised state envelope refused an entry.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum EnvelopeError {
    /// The tick did not strictly follow the last one, so the envelope would no
    /// longer be the ordered record of a forward-moving run.
    NonIncreasingTick {
        /// The last tick the envelope holds.
        last: Tick,
        /// The tick that was refused.
        received: Tick,
    },
    /// The envelope holds more entries than [`MAX_ENVELOPE_ENTRIES`].
    TooManyEntries {
        /// The bound.
        max: usize,
    },
}

impl fmt::Display for EnvelopeError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::NonIncreasingTick { last, received } => write!(
                f,
                "tick {} does not follow the envelope's last tick {}",
                received.0, last.0
            ),
            Self::TooManyEntries { max } => {
                write!(f, "an envelope may hold at most {max} state hashes")
            }
        }
    }
}

impl std::error::Error for EnvelopeError {}

/// Why a capture record refused a camera, a render configuration or a
/// comparison.
///
/// `PartialEq` and not `Eq` because [`CaptureError::FieldOfView`] carries the
/// rejected angle, and a float is never `Eq` — which is why the accepted range
/// is checked rather than the value compared.
#[derive(Clone, Debug, PartialEq)]
pub enum CaptureError {
    /// A camera component was NaN or infinite.
    NonFinite {
        /// The offending component.
        field: &'static str,
    },
    /// A vertical field of view was not strictly inside `(0, PI)`.
    FieldOfView {
        /// The rejected value, in radians.
        value: f64,
    },
    /// A render dimension was zero or beyond the declared bound.
    RenderDimension {
        /// Which dimension.
        field: &'static str,
        /// The rejected value.
        value: u32,
    },
    /// A render setting fell outside its declared designed range.
    RenderRange {
        /// The offending field.
        field: &'static str,
        /// The rejected value.
        value: u32,
    },
    /// The capture came from a build that is not the replay's build.
    BuildMismatch {
        /// The replay's build id.
        replay: BuildId,
        /// The capture's build id.
        capture: BuildId,
    },
    /// The capture names a replay other than the one it was taken from.
    ReplayMismatch {
        /// The replay's compatibility signature.
        replay: ContentHash,
        /// The capture's recorded signature.
        capture: ContentHash,
    },
    /// Two captures differ, so they cannot be compared as equal.
    Difference(CaptureDifference),
}

impl fmt::Display for CaptureError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::NonFinite { field } => write!(f, "camera {field} must be finite"),
            Self::FieldOfView { value } => write!(
                f,
                "a vertical field of view must be inside (0, pi) radians, got {value}"
            ),
            Self::RenderDimension { field, value } => {
                write!(
                    f,
                    "render {field} {value} is outside 1..={MAX_RENDER_DIMENSION}"
                )
            }
            Self::RenderRange { field, value } => {
                write!(f, "render {field} {value} is outside its designed range")
            }
            Self::BuildMismatch { replay, capture } => write!(
                f,
                "the capture was made by build {capture}, not the replay's build {replay}"
            ),
            Self::ReplayMismatch { replay, capture } => write!(
                f,
                "the capture names replay {capture}, not the replay's signature {replay}"
            ),
            Self::Difference(difference) => write!(f, "{difference}"),
        }
    }
}

impl std::error::Error for CaptureError {}

