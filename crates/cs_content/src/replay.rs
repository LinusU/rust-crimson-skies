/// One consumer's derived stream seed.
#[derive(Clone, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub struct SeedStream {
    /// The consumer's name, e.g. `synthetic_body`.
    pub label: String,
    /// The derived stream seed.
    pub seed: u64,
}

/// A run's root seed and the derived stream seeds of its consumers.
///
/// The contract (`docs/contracts/CLI-EVIDENCE.md`, section "`--seed`") fixes
/// the derivation: a consumer's stream seed is the SplitMix64 output of
/// `root_seed ^ DOMAIN`, and every consumer owns its own documented domain
/// constant so adding one never moves another's values. [`ReplaySeeds::derive`]
/// performs exactly that derivation, so a replay records the streams it
/// actually consumed instead of a root seed a reader would have to re-derive
/// with the wrong domain list.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct ReplaySeeds {
    root: u64,
    streams: Vec<SeedStream>,
}

impl ReplaySeeds {
    /// Wraps a root seed and its derived streams, refusing a repeated label.
    ///
    /// # Errors
    ///
    /// [`ReplayError::Duplicate`] for a label held twice and
    /// [`ReplayError::TooManyEntries`] above [`MAX_SEED_STREAMS`].
    pub fn new(root: u64, mut streams: Vec<SeedStream>) -> Result<Self, ReplayError> {
        if streams.len() > MAX_SEED_STREAMS {
            return Err(ReplayError::TooManyEntries {
                what: "seed streams",
                max: MAX_SEED_STREAMS,
            });
        }
        streams.sort();
        for pair in streams.windows(2) {
            if pair[0].label == pair[1].label {
                return Err(ReplayError::Duplicate {
                    what: "seed stream",
                    key: pair[0].label.clone(),
                });
            }
        }
        Ok(Self { root, streams })
    }

    /// Derives one stream seed per consumer from `root` with the contract's
    /// recipe, given each consumer's `(domain constant, label)` pair.
    ///
    /// The result is sorted by label, so two calls with the same consumers in a
    /// different order are the same record.
    pub fn derive(root: u64, consumers: &[(u64, &str)]) -> Result<Self, ReplayError> {
        let streams = consumers
            .iter()
            .map(|(domain, label)| {
                let label = check_label("seed stream label", label)?;
                if label.len() > MAX_SEED_LABEL_BYTES {
                    return Err(ReplayError::TooLong {
                        field: "seed stream label",
                        len: label.len(),
                        max: MAX_SEED_LABEL_BYTES,
                    });
                }
                let seed = SplitMix64::for_domain(root, *domain).next_u64();
                Ok(SeedStream { label, seed })
            })
            .collect::<Result<Vec<_>, _>>()?;
        Self::new(root, streams)
    }

    /// The root seed of the run.
    pub fn root(&self) -> u64 {
        self.root
    }

    /// The derived streams, sorted by label.
    pub fn streams(&self) -> &[SeedStream] {
        &self.streams
    }

    /// The derived seed of one named consumer.
    pub fn stream(&self, label: &str) -> Option<u64> {
        self.streams
            .iter()
            .find(|stream| stream.label == label)
            .map(|stream| stream.seed)
    }

    /// A digest over the whole seed record, so a changed seed is visible in
    /// the compatibility signature and in a difference report.
    pub fn digest(&self) -> ContentHash {
        let mut hasher = Sha256::new();
        hasher.update(SEED_DOMAIN);
        put_u64(&mut hasher, self.root);
        put_u64(&mut hasher, self.streams.len() as u64);
        for stream in &self.streams {
            put_text(&mut hasher, &stream.label);
            put_u64(&mut hasher, stream.seed);
        }
        hasher.finalize()
    }
}

