/// One evidence artifact: a claim, the task that produced it, where the bytes
/// live and what they hash to.
///
/// The record carries a **path and a digest**, never content: the artifacts
/// themselves stay in the owner's private directory, and the committed copy of
/// a report is hashes and paths only. [`EvidenceArtifact::new`] enforces that
/// the path is private-relative, so a report cannot smuggle an original asset
/// into the public repository by naming it.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct EvidenceArtifact {
    /// The claim this artifact is evidence for.
    pub claim: ClaimId,
    /// The task that produced it, e.g. `F59-C`.
    pub task: String,
    /// The artifact's path, relative to the private evidence directory.
    pub path: String,
    /// The SHA-256 of the produced bytes.
    pub sha256: ContentHash,
    /// What the artifact is.
    pub media: ArtifactMedia,
    /// Who produced the bytes.
    pub origin: ArtifactOrigin,
    /// What the recorder hashed to stand behind this artifact: the artifact
    /// itself, the canonical content, or the owner's installation.
    pub fingerprint: Fingerprint,
    /// Where inside the fingerprinted source the observation lives.
    pub locator: String,
}

/// What an artifact *is*, as a caller describes it before validation.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ArtifactDescription<'a> {
    /// The claim it is evidence for.
    pub claim: &'a ClaimId,
    /// The task that produced it.
    pub task: &'a str,
    /// Its path, relative to the private evidence directory.
    pub path: &'a str,
    /// The SHA-256 of the produced bytes.
    pub sha256: ContentHash,
    /// What the artifact is.
    pub media: ArtifactMedia,
    /// Who produced the bytes.
    pub origin: ArtifactOrigin,
    /// What the recorder hashed to stand behind it.
    pub fingerprint: Fingerprint,
    /// Where inside the fingerprinted source the observation lives.
    pub locator: &'a str,
}

impl EvidenceArtifact {
    /// Validates and wraps an artifact link.
    ///
    /// # Errors
    ///
    /// [`ReplayError::Blank`] for an empty task, path or locator,
    /// [`ReplayError::TooLong`] for an oversized field, and
    /// [`ReplayError::Syntax`] for a path that is absolute or escapes the
    /// private directory.
    pub fn new(described: ArtifactDescription<'_>) -> Result<Self, ReplayError> {
        let task = check_label("task id", described.task)?;
        if task.len() > MAX_LABEL_BYTES {
            return Err(ReplayError::TooLong {
                field: "task id",
                len: task.len(),
                max: MAX_LABEL_BYTES,
            });
        }
        check_private_path(described.path)?;
        check_text("observation locator", described.locator)?;
        Ok(Self {
            claim: described.claim.clone(),
            task,
            path: described.path.to_owned(),
            sha256: described.sha256,
            media: described.media,
            origin: described.origin,
            fingerprint: described.fingerprint,
            locator: described.locator.to_owned(),
        })
    }

    /// The `cs_types::evidence` record this artifact is, or would be, as
    /// evidence.
    ///
    /// The origin decides the observation method, which is the whole point of
    /// the mapping: an [`ArtifactOrigin::Authored`] artifact becomes
    /// [`ObservationMethod::Authored`], and
    /// [`EvidenceRecord::verifies_original`] then refuses it however it was
    /// labelled or fingerprinted. A hand-drawn PNG attached to a fingerprinted
    /// installation is exactly the shortcut the contract forbids.
    pub fn evidence_record(&self, tool: &str, tool_version: &str) -> EvidenceRecord {
        EvidenceRecord {
            source: EvidenceSource::ToolRun {
                tool: tool.to_owned(),
                version: tool_version.to_owned(),
            },
            fingerprint: Some(self.fingerprint),
            locator: Some(ObservationLocator {
                container: format!("{}#{}", self.task, self.locator),
                span: None,
            }),
            method: self.origin.observation_method(),
            limitations: self.limitations(),
        }
    }

    /// The limitations this artifact carries by construction.
    ///
    /// A decoded PCM capture always states that it is a decode artifact and
    /// not audible playback review, so the limitation travels with the record
    /// instead of living in a report somebody forgot to write.
    #[must_use]
    pub fn limitations(&self) -> Vec<String> {
        let mut limitations = Vec::new();
        match self.media {
            ArtifactMedia::PcmCapture(PcmRole::DecodeOnly) => limitations.push(
                "samples were decoded without an audio device: a decode artifact, not audible \
                 playback review"
                    .to_owned(),
            ),
            ArtifactMedia::PcmCapture(PcmRole::AudiblePlayback) => limitations.push(
                "audible playback still requires human review; playing a file is not listening to \
                 it"
                .to_owned(),
            ),
            ArtifactMedia::Screenshot => limitations.push(
                "a rendered frame is visual evidence only; it says nothing about ordinary play"
                    .to_owned(),
            ),
            ArtifactMedia::Trace | ArtifactMedia::Report => {}
        }
        if self.origin == ArtifactOrigin::Authored {
            limitations.push(
                "the bytes were authored, not produced by runtime code: this artifact cannot \
                 support verified_original"
                    .to_owned(),
            );
        }
        limitations
    }

    /// The capability this artifact's media requires, whether or not the
    /// machine has it.
    pub fn required_capabilities(&self) -> &'static [CapabilityClass] {
        self.media.required_capabilities()
    }
}

/// Checks that an artifact path is private-relative: not absolute, no drive
/// letter, no `..` component, and no empty component.
fn check_private_path(path: &str) -> Result<(), ReplayError> {
    if path.trim().is_empty() {
        return Err(ReplayError::Blank {
            field: "artifact path",
        });
    }
    if path.len() > MAX_VALUE_BYTES {
        return Err(ReplayError::TooLong {
            field: "artifact path",
            len: path.len(),
            max: MAX_VALUE_BYTES,
        });
    }
    if path.starts_with('/') || path.starts_with('\\') || path.contains(':') {
        return Err(ReplayError::Syntax {
            field: "artifact path",
            reason: "an artifact path is relative to the private evidence directory",
        });
    }
    if path
        .split(['/', '\\'])
        .any(|component| component.is_empty() || component == "..")
    {
        return Err(ReplayError::Syntax {
            field: "artifact path",
            reason: "an artifact path may not contain an empty or `..` component",
        });
    }
    Ok(())
}

/// The test counts an actual run reported.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct TestCounts {
    pub passed: u32,
    pub failed: u32,
    pub assertions: u32,
}

impl TestCounts {
    /// Whether the run actually passed: at least one test, none failed.
    pub const fn is_pass(&self) -> bool {
        self.failed == 0 && self.passed > 0
    }
}

/// The build an evidence report is being checked against.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct CandidateBuild {
    /// The candidate tree hash of the commit being tested.
    pub tree: BuildId,
    /// The canonical content digest of that build.
    pub content_sha256: ContentHash,
}

/// The record minimum of `docs/contracts/CLI-EVIDENCE.md`, "Evidence record
/// minimum", as a type: task id, candidate tree, engine/toolchain versions,
/// test command, counts, capability class, the artifacts, the overrides and the
/// unresolved issues.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct EvidenceBundle {
    /// The task this bundle reports on.
    pub task: String,
    /// The candidate tree hash the run was made on.
    pub tree: BuildId,
    /// The canonical content digest the run loaded.
    pub content_sha256: ContentHash,
    /// The installation digest, when the run touched the original data.
    pub install_sha256: Option<ContentHash>,
    /// The tool or engine that produced the run.
    pub tool: String,
    /// Its version.
    pub tool_version: String,
    /// The test command as it was run, argv included.
    pub test_command: String,
    /// The counts the run reported.
    pub counts: TestCounts,
    /// What the machine declares it can do.
    pub capabilities: DeclaredCapabilities,
    /// The run's purpose, debug overrides and profile-write request.
    pub overrides: OverrideLog,
    /// The artifacts, each linking a claim to bytes in the private directory.
    pub artifacts: Vec<EvidenceArtifact>,
    /// Issues the run left unresolved. A report never deletes one to pass a
    /// validator.
    pub unresolved: Vec<String>,
}

impl EvidenceBundle {
    /// Checks the bundle's own bounds.
    ///
    /// # Errors
    ///
    /// [`ReplayError::Blank`] or [`ReplayError::TooLong`] for an empty or
    /// oversized field, [`ReplayError::TooManyEntries`] above
    /// [`MAX_ARTIFACTS`], and [`ReplayError::Blank`] for an empty unresolved
    /// issue.
    pub fn validate(&self) -> Result<(), ReplayError> {
        check_label("task id", &self.task)?;
        check_text("tool", &self.tool)?;
        check_text("tool version", &self.tool_version)?;
        check_text("test command", &self.test_command)?;
        if self.artifacts.len() > MAX_ARTIFACTS {
            return Err(ReplayError::TooManyEntries {
                what: "artifacts",
                max: MAX_ARTIFACTS,
            });
        }
        for issue in &self.unresolved {
            check_text("unresolved issue", issue)?;
        }
        Ok(())
    }

    /// The evidence record of one artifact, in this bundle's terms.
    pub fn evidence_record(&self, artifact: &EvidenceArtifact) -> EvidenceRecord {
        artifact.evidence_record(&self.tool, &self.tool_version)
    }

    /// Checks the bundle against the build it claims to certify.
    ///
    /// The report is a list, not a bare verdict, because every problem has to
    /// be visible: a missing capability, a stale tree, a hand-made artifact and
    /// a run with debug overrides are four different reasons a claim does not
    /// stand, and collapsing them into "failed" would hide which.
    /// [`CertificationReport::is_checked`] is the single question, and it is
    /// true only when every list is empty and the run actually passed.
    #[must_use]
    pub fn certify(&self, candidate: &CandidateBuild) -> CertificationReport {
        let mut report = CertificationReport {
            counts: self.counts,
            ..CertificationReport::default()
        };

        if self.tree != candidate.tree {
            report.stale.push(StaleReason::TreeChanged {
                recorded: self.tree.clone(),
                candidate: candidate.tree.clone(),
            });
        }
        if self.content_sha256 != candidate.content_sha256 {
            report.stale.push(StaleReason::ContentChanged {
                recorded: self.content_sha256,
                candidate: candidate.content_sha256,
            });
        }
        if self.capabilities.contains(CapabilityClass::Retail) && self.install_sha256.is_none() {
            report
                .stale
                .push(StaleReason::RetailWithoutInstallationHash);
        }

        if self.overrides.violates_profile_rule() {
            report
                .refused
                .push(EvidenceRefusal::ProfileWriteDuringCapture {
                    task: self.task.clone(),
                });
        }

        let mut claim_state: BTreeMap<ClaimId, ClaimStanding> = BTreeMap::new();
        for artifact in &self.artifacts {
            let standing = claim_state.entry(artifact.claim.clone()).or_default();
            for required in artifact.required_capabilities() {
                if !self.capabilities.contains(*required) {
                    standing.blocked = true;
                    report.blocked.push(CapabilityGap {
                        claim: artifact.claim.clone(),
                        required: *required,
                    });
                }
            }
            if artifact.origin == ArtifactOrigin::Authored {
                standing.refused = true;
                report.refused.push(EvidenceRefusal::AuthoredArtifact {
                    claim: artifact.claim.clone(),
                    path: artifact.path.clone(),
                });
            }
            if artifact.task != self.task {
                standing.refused = true;
                report.refused.push(EvidenceRefusal::ForeignTask {
                    claim: artifact.claim.clone(),
                    task: artifact.task.clone(),
                });
            }
        }
        report.certified = claim_state
            .into_iter()
            .filter(|(_, standing)| !standing.blocked && !standing.refused)
            .map(|(claim, _)| claim)
            .collect();
        if self.overrides.invalidates_ordinary_play() {
            report.ordinary_play_refused.push(OrdinaryPlayRefusal {
                purpose: self.overrides.purpose(),
                overrides: self.overrides.entries().to_vec(),
            });
        }
        report
    }
}

/// Why a report cannot certify a build.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum StaleReason {
    /// The report was produced on a different candidate tree.
    TreeChanged {
        /// The tree the report names.
        recorded: BuildId,
        /// The tree being certified.
        candidate: BuildId,
    },
    /// The report was produced against different content.
    ContentChanged {
        /// The content digest the report names.
        recorded: ContentHash,
        /// The content digest of the build being certified.
        candidate: ContentHash,
    },
    /// The run declares `retail` access but names no installation digest, so
    /// the original data it claims to have read cannot be identified.
    RetailWithoutInstallationHash,
}

impl fmt::Display for StaleReason {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::TreeChanged {
                recorded,
                candidate,
            } => write!(
                f,
                "the report names tree {recorded}, not the candidate's {candidate}"
            ),
            Self::ContentChanged {
                recorded,
                candidate,
            } => write!(
                f,
                "the report names content {recorded}, not the candidate's {candidate}"
            ),
            Self::RetailWithoutInstallationHash => write!(
                f,
                "a run that declares retail access must name the installation digest it read"
            ),
        }
    }
}

/// A capability an artifact needs that the machine does not declare.
#[derive(Clone, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub struct CapabilityGap {
    pub claim: ClaimId,
    pub required: CapabilityClass,
}

impl fmt::Display for CapabilityGap {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(
            f,
            "claim {} needs capability {} which this machine does not declare",
            self.claim, self.required
        )
    }
}

/// Why an artifact cannot be reported as evidence of anything.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum EvidenceRefusal {
    /// The artifact's bytes were authored, not produced by runtime code.
    AuthoredArtifact {
        /// The claim it was attached to.
        claim: ClaimId,
        /// Where the bytes live.
        path: String,
    },
    /// The artifact names a different task than the bundle it sits in.
    ForeignTask {
        /// The claim it was attached to.
        claim: ClaimId,
        /// The task it names.
        task: String,
    },
    /// A capture/probe run wrote a production profile without asking for it.
    ProfileWriteDuringCapture {
        /// The task that did it.
        task: String,
    },
}

impl fmt::Display for EvidenceRefusal {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::AuthoredArtifact { claim, path } => write!(
                f,
                "artifact {path:?} for claim {claim} was authored, not produced by runtime code"
            ),
            Self::ForeignTask { claim, task } => write!(
                f,
                "artifact for claim {claim} names task {task}, not this bundle's task"
            ),
            Self::ProfileWriteDuringCapture { task } => write!(
                f,
                "task {task} ran a capture/probe that wrote a production profile without \
                 requesting it"
            ),
        }
    }
}

/// Whether one claim is still standing after every artifact attached to it
/// has been examined.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
struct ClaimStanding {
    /// At least one artifact needed a capability this machine does not have.
    blocked: bool,
    /// At least one artifact was refused (authored bytes, or another task's
    /// artifact).
    refused: bool,
}

/// Why a run cannot be presented as ordinary play.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct OrdinaryPlayRefusal {
    pub purpose: RunPurpose,
    pub overrides: Vec<OverrideEntry>,
}

impl fmt::Display for OrdinaryPlayRefusal {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self.overrides.as_slice() {
            [] => write!(f, "the run was a {} run, not ordinary play", self.purpose),
            overrides => {
                let names = overrides
                    .iter()
                    .map(|entry| entry.name.as_str())
                    .collect::<Vec<_>>()
                    .join(", ");
                write!(
                    f,
                    "the run was a {} run with debug overrides ({names}), not ordinary play",
                    self.purpose
                )
            }
        }
    }
}

/// The full result of checking an evidence bundle against a candidate build.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct CertificationReport {
    /// The counts the run reported.
    pub counts: TestCounts,
    /// Reasons the report is stale for this candidate.
    pub stale: Vec<StaleReason>,
    /// Capabilities an artifact needed that the machine did not declare.
    pub blocked: Vec<CapabilityGap>,
    /// Artifacts that cannot be evidence of what they were attached to.
    pub refused: Vec<EvidenceRefusal>,
    /// Why the run is not ordinary play.
    pub ordinary_play_refused: Vec<OrdinaryPlayRefusal>,
    /// The claims whose artifacts are all runtime-produced, capability-backed
    /// and free of other refusals.
    pub certified: Vec<ClaimId>,
}

impl CertificationReport {
    /// Whether the report certifies anything at all.
    ///
    /// Every list has to be empty *and* the run has to have passed: a report
    /// that could not be checked is not a pass, and a run that failed is not a
    /// pass, and a headless run that claims a screenshot is blocked rather
    /// than certified. There is no path from "we could not tell" to `true`.
    pub fn is_checked(&self) -> bool {
        matches!(self.certification(), Certification::Checked { .. })
    }

    /// What the report concluded, in one value.
    ///
    /// The order is deliberate: a run that did not pass is reported as not
    /// passing before anything else is examined, and a stale report is
    /// reported as stale before its artifacts are judged, because neither
    /// question is about the artifacts.
    pub fn certification(&self) -> Certification {
        if !self.counts.is_pass() {
            return Certification::NotPassed {
                failed: self.counts.failed,
                passed: self.counts.passed,
            };
        }
        if !self.stale.is_empty() {
            return Certification::Stale {
                reasons: self.stale.len(),
            };
        }
        if !self.blocked.is_empty() {
            return Certification::Blocked {
                gaps: self.blocked.len(),
            };
        }
        if !self.refused.is_empty() {
            return Certification::Refused {
                reasons: self.refused.len(),
            };
        }
        if !self.ordinary_play_refused.is_empty() {
            return Certification::NotOrdinaryPlay;
        }
        if self.certified.is_empty() {
            return Certification::NoClaims;
        }
        Certification::Checked {
            claims: self.certified.clone(),
        }
    }

    /// One stderr-suitable diagnostic line per problem, in report order.
    pub fn diagnostic_lines(&self) -> Vec<String> {
        let mut lines = Vec::new();
        lines.push(format!(
            "certification: {}; tests {}/{} failed={} assertions={}",
            self.certification(),
            self.counts.passed,
            self.counts.passed + self.counts.failed,
            self.counts.failed,
            self.counts.assertions
        ));
        for reason in &self.stale {
            lines.push(format!("stale: {reason}"));
        }
        for gap in &self.blocked {
            lines.push(format!("blocked: {gap}"));
        }
        for refusal in &self.refused {
            lines.push(format!("refused: {refusal}"));
        }
        for refusal in &self.ordinary_play_refused {
            lines.push(format!("not ordinary play: {refusal}"));
        }
        for claim in &self.certified {
            lines.push(format!("certified: claim {claim}"));
        }
        lines
    }
}

/// The one-line conclusion of a [`CertificationReport`].
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Certification {
    /// Every claim stands, at the `checked` level and nothing above it.
    Checked {
        /// The claims the report covers.
        claims: Vec<ClaimId>,
    },
    /// The run did not pass.
    NotPassed {
        /// How many tests failed.
        failed: u32,
        /// How many passed.
        passed: u32,
    },
    /// The report does not describe the candidate build.
    Stale {
        /// How many stale reasons there are.
        reasons: usize,
    },
    /// A capability the artifacts need is not available here.
    Blocked {
        /// How many capability gaps there are.
        gaps: usize,
    },
    /// An artifact cannot be evidence of what it was attached to.
    Refused {
        /// How many refusals there are.
        reasons: usize,
    },
    /// The run is not ordinary play, so it cannot be ordinary-play proof.
    NotOrdinaryPlay,
    /// Nothing was attached to certify.
    NoClaims,
}

impl fmt::Display for Certification {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Checked { claims } => {
                write!(
                    f,
                    "checked ({} claim(s), not verified_original)",
                    claims.len()
                )
            }
            Self::NotPassed { failed, passed } => {
                write!(f, "not passed ({failed} failed, {passed} passed)")
            }
            Self::Stale { reasons } => write!(f, "stale ({reasons} reason(s))"),
            Self::Blocked { gaps } => write!(f, "blocked ({gaps} capability gap(s))"),
            Self::Refused { reasons } => write!(f, "refused ({reasons} reason(s))"),
            Self::NotOrdinaryPlay => write!(f, "not ordinary play"),
            Self::NoClaims => write!(f, "no claims"),
        }
    }
}

