/// One tick's promised state hash.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub struct StateEntry {
    /// The simulation tick the hash describes.
    pub tick: Tick,
    /// The hash of the state at that tick, as the runtime measured it.
    pub state: ContentHash,
}

/// The ordered per-tick state hashes a replay promises to reproduce.
///
/// This is the "envelope" of the sheet's AC01. Two properties make it useful
/// rather than decorative: the ticks are strictly increasing, so a gap is a
/// fact about the run rather than an accident of ordering; and
/// [`chain_digest`](Self::chain_digest) folds the whole sequence — plus the
/// initial state it starts from — into one digest that changes if any entry
/// changes, moves or disappears.
///
/// The hashes themselves are measured by a running session (F59-B). This
/// module never produces a state hash from anything but a real measurement or
/// an explicitly synthetic fixture description.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct StateEnvelope {
    entries: Vec<StateEntry>,
}

impl StateEnvelope {
    /// An empty envelope.
    #[must_use]
    pub fn new() -> Self {
        Self::default()
    }

    /// Appends one tick's state hash.
    ///
    /// # Errors
    ///
    /// [`EnvelopeError::NonIncreasingTick`] when `tick` does not follow the
    /// last recorded tick, and [`EnvelopeError::TooManyEntries`] above
    /// [`MAX_ENVELOPE_ENTRIES`]. A refused entry changes nothing.
    pub fn push(&mut self, tick: Tick, state: ContentHash) -> Result<(), EnvelopeError> {
        if let Some(last) = self.last_tick()
            && tick <= last
        {
            return Err(EnvelopeError::NonIncreasingTick {
                last,
                received: tick,
            });
        }
        if self.entries.len() >= MAX_ENVELOPE_ENTRIES {
            return Err(EnvelopeError::TooManyEntries {
                max: MAX_ENVELOPE_ENTRIES,
            });
        }
        self.entries.push(StateEntry { tick, state });
        Ok(())
    }

    /// The recorded hashes, oldest first.
    pub fn entries(&self) -> &[StateEntry] {
        &self.entries
    }

    /// How many ticks are recorded.
    pub fn len(&self) -> usize {
        self.entries.len()
    }

    /// Whether nothing is recorded.
    pub fn is_empty(&self) -> bool {
        self.entries.is_empty()
    }

    /// The first recorded tick.
    pub fn first_tick(&self) -> Option<Tick> {
        self.entries.first().map(|entry| entry.tick)
    }

    /// The last recorded tick.
    pub fn last_tick(&self) -> Option<Tick> {
        self.entries.last().map(|entry| entry.tick)
    }

    /// The hash recorded for one tick.
    pub fn entry(&self, tick: Tick) -> Option<StateEntry> {
        self.entries
            .iter()
            .copied()
            .find(|entry| entry.tick == tick)
    }

    /// Folds the envelope into one digest, chained from the run's initial
    /// state.
    ///
    /// Each step hashes the previous chain value, the tick and that tick's
    /// state hash, so the digest binds the *order* of the run as well as its
    /// contents: two envelopes with the same hashes at different ticks do not
    /// share a digest.
    pub fn chain_digest(&self, initial_state: ContentHash) -> ContentHash {
        let mut hasher = Sha256::new();
        hasher.update(ENVELOPE_CHAIN_DOMAIN);
        put_hash(&mut hasher, initial_state);
        put_u64(&mut hasher, self.entries.len() as u64);
        for entry in &self.entries {
            put_u64(&mut hasher, entry.tick.0);
            put_hash(&mut hasher, entry.state);
        }
        hasher.finalize()
    }

    /// Compares two envelopes tick by tick and reports the first difference.
    ///
    /// The comparison stops at the first difference rather than collecting all
    /// of them: a divergence at tick 12 tells a reader where the two runs part
    /// company, and the whole vector of differences is noise next to it.
    /// `compared_ticks` says how far the identical prefix reached.
    #[must_use]
    pub fn compare(&self, other: &Self) -> EnvelopeComparison {
        let mut compared = 0usize;
        for (left, right) in self.entries.iter().zip(other.entries.iter()) {
            if left.tick != right.tick {
                return EnvelopeComparison {
                    compared_ticks: compared,
                    divergence: Some(Divergence {
                        tick: Some(left.tick),
                        reason: DivergenceReason::Tick {
                            expected: left.tick,
                            observed: right.tick,
                        },
                    }),
                };
            }
            if left.state != right.state {
                return EnvelopeComparison {
                    compared_ticks: compared,
                    divergence: Some(Divergence {
                        tick: Some(left.tick),
                        reason: DivergenceReason::State {
                            expected: left.state,
                            observed: right.state,
                        },
                    }),
                };
            }
            compared += 1;
        }
        if self.entries.len() != other.entries.len() {
            return EnvelopeComparison {
                compared_ticks: compared,
                divergence: Some(Divergence {
                    tick: None,
                    reason: DivergenceReason::Length {
                        expected: self.entries.len(),
                        observed: other.entries.len(),
                    },
                }),
            };
        }
        EnvelopeComparison {
            compared_ticks: compared,
            divergence: None,
        }
    }
}

/// The outcome of comparing two [`StateEnvelope`]s.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct EnvelopeComparison {
    /// How many leading ticks were identical before the comparison stopped.
    pub compared_ticks: usize,
    /// The first difference, or `None` when the two envelopes are identical.
    pub divergence: Option<Divergence>,
}

impl EnvelopeComparison {
    /// Whether the two envelopes are identical.
    pub fn is_identical(&self) -> bool {
        self.divergence.is_none()
    }

    /// The first tick at which the two envelopes differ, when they do.
    pub fn first_divergent_tick(&self) -> Option<Tick> {
        self.divergence
            .as_ref()
            .and_then(|divergence| divergence.tick)
    }
}

/// One difference between two state envelopes.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Divergence {
    /// The tick the difference was found at, or `None` when the envelopes
    /// differ in length only.
    pub tick: Option<Tick>,
    /// What differed.
    pub reason: DivergenceReason,
}

impl fmt::Display for Divergence {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self.reason {
            DivergenceReason::State { expected, observed } => write!(
                f,
                "state hash at tick {} is {observed}, not the promised {expected}",
                self.tick.map(|tick| tick.0).unwrap_or_default()
            ),
            DivergenceReason::Tick { observed, .. } => write!(
                f,
                "tick {} carries the observed tick {}",
                self.tick.map(|tick| tick.0).unwrap_or_default(),
                observed.0
            ),
            DivergenceReason::Length { expected, observed } => {
                write!(f, "the envelope holds {observed} hashes, not {expected}")
            }
            DivergenceReason::OutsideRange { tick, first, last } => write!(
                f,
                "tick {} is outside the run's declared range {}..={}",
                tick.0, first.0, last.0
            ),
        }
    }
}

/// What differed between two envelopes.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum DivergenceReason {
    /// The same tick carries different state hashes.
    State {
        /// The promised hash.
        expected: ContentHash,
        /// The observed hash.
        observed: ContentHash,
    },
    /// The same position in the sequence carries different ticks.
    Tick {
        /// The promised tick.
        expected: Tick,
        /// The observed tick.
        observed: Tick,
    },
    /// The envelopes have different lengths; every common tick matched.
    Length {
        /// The promised number of hashes.
        expected: usize,
        /// The observed number of hashes.
        observed: usize,
    },
    /// An observed tick lies outside the run's declared tick range, so it
    /// cannot be this replay's run at all.
    OutsideRange {
        /// The offending tick.
        tick: Tick,
        /// The declared first tick.
        first: Tick,
        /// The declared last tick.
        last: Tick,
    },
}

