//! Replay, capture and acceptance-evidence records (F59-A).
//!
//! Spec: `specs/F59-replays-captures-probes-and-acceptance-evidence.md`,
//! stage `### F59-A`. Shared contract: `docs/contracts/CLI-EVIDENCE.md`
//! (sections "App", "Evidence record minimum", "Verification levels",
//! "Negative tests are mandatory" and "Report production during trusted
//! gates").
//!
//! This is the **content half** of F59: the engine-free, provenance-carrying
//! records a run writes and a report reads. It follows the same split the
//! other contracts use — the declared, Bevy-free record lives in
//! `cs_content` and the code that produces or renders it lives in
//! `cs_app::capture` (F59-B) and the `cs-inspect`/`cs_xtask` commands
//! (F59-C). Nothing here simulates, renders, opens a device or touches the
//! filesystem: this module defines the typed inputs and outputs, their
//! bounded on-disk form and the checks that make a record mean what it claims.
//!
//! # What a replay records
//!
//! The sheet's deliverable line is exact: "Replay records engine/content/
//! rules fingerprint, initial state, input stream, seeds, tick rate and
//! relevant authored choices." [`ReplayRecord`] carries one of each, and
//! nothing it does not:
//!
//! * [`BuildFingerprint`] — the candidate [`BuildId`] (tree hash), the engine,
//!   content and rules digests, the toolchain string and the
//!   [`PlatformTag`]. The three digests are separate because a content asset
//!   changing (AC02) is a different failure from a rules table changing, and
//!   a report that hashed them into one number could not say which happened.
//! * [`InitialState`] — a label and the digest of the state the run started
//!   from. The digest is *supplied* by the runtime (F59-B measures it from a
//!   real run); this module never invents one.
//! * [`CommandStream`] — the quantized, tick-stamped `cs_types::input` record
//!   the input boundary already produces, so a replay replays exactly what
//!   the player did at any display rate. It is digested by
//!   [`InputStreamDigest`].
//! * [`ReplaySeeds`] — the root seed and the derived, domain-separated stream
//!   seeds, so a replay names the exact random streams it consumed.
//! * `tick_rate`, `first_tick`, `last_tick` — the fixed rate and the run's
//!   tick range, in whole ticks ([`cs_types::Tick`]) and nothing else.
//! * [`AuthoredChoices`] — the authored decisions a replay must pin (airframe,
//!   difficulty, loadout, assists, mission, ruleset), each with its
//!   [`Provenance`], so a replay cannot silently assume one.
//!
//! # What a capture records
//!
//! [`CaptureRecord`] carries the exact [`CaptureCamera`], the capture tick,
//! the whole [`RenderConfig`], the build hash of the producing binary, the
//! compatibility signature of the replay it came from and the digest of the
//! bytes it produced, plus the [`ArtifactOrigin`] that says *who* made those
//! bytes. [`CaptureRecord::compare`] refuses to call two captures equal while
//! any of those differ, and [`CaptureRecord::digest`] is the one-line
//! statement of "the same camera, the same tick, the same renderer, the same
//! bytes" (AC03).
//!
//! # The five non-negotiable behaviors, structurally
//!
//! 1. *Same-build replay is the initial determinism target; cross-version or
//!    cross-platform replay is rejected or explicitly best-effort.* There is
//!    no default that is "probably fine": [`CrossBuildPolicy::Reject`] refuses
//!    any difference, and [`CrossBuildPolicy::BestEffort`] is a verdict of
//!    its own ([`CompatibilityVerdict::BestEffort`]) that names the
//!    differences and, by construction, certifies no determinism
//!    ([`CompatibilityVerdict::certifies_determinism`]).
//! 2. *A screenshot, PCM capture or trace is generated by production runtime
//!    code.* [`ArtifactOrigin::Authored`] is a first-class value, and
//!    [`EvidenceArtifact::evidence_record`] maps it to
//!    [`ObservationMethod::Authored`], so a hand-drawn image attached to a
//!    fingerprinted installation cannot pass
//!    [`EvidenceRecord::verifies_original`] however it is labelled.
//! 3. *Headless simulation, GPU render and audible output are distinct
//!    capabilities; a missing capability yields BLOCKED, not skipped-pass.*
//!    [`ArtifactMedia::required_capabilities`] is a table, not an inference:
//!    a [`ArtifactMedia::Screenshot`] needs `gpu`, an audible PCM capture
//!    needs `audio` **and** `human_review`, and
//!    [`EvidenceBundle::certify`] turns every missing capability into a
//!    [`CapabilityGap`], so a headless machine can only ever produce
//!    [`Certification::Blocked`].
//! 4. *No normal campaign profile writes during capture/probe runs unless
//!    explicitly requested; debug overrides invalidate ordinary-play proof.*
//!    [`OverrideLog`] records the run's [`RunPurpose`], its named debug
//!    overrides and whether a production profile write was requested.
//!    [`OverrideLog::violates_profile_rule`] is the capture/probe rule and
//!    [`OverrideLog::invalidates_ordinary_play`] the debug-override rule;
//!    either one removes an ordinary-play claim from a certification.
//! 5. *Evidence freshness binds to tree hash, test command, content hash and
//!    result; a stale report cannot certify a new build.*
//!    [`EvidenceBundle::certify`] takes a [`CandidateBuild`] and reports
//!    [`StaleReason::TreeChanged`] / [`StaleReason::ContentChanged`] instead
//!    of a pass.
//!
//! # On-disk form
//!
//! [`encode`]/[`decode`] and [`encode_capture`]/[`decode_capture`] are bounded,
//! checksummed line documents, the same durability discipline
//! `cs_content::save` uses: a fixed maximum size and line count, UTF-8 only, a
//! `CSREPLAY`/`CSCAPTURE` header whose major version must be readable, and a
//! trailing SHA-256 `checksum=` line over every byte above it. Unknown lines
//! of a readable major are preserved in [`ReplayRecord::extra`] and
//! re-emitted, so a newer minor's document survives a round trip through an
//! older build. A different major is refused, never merged or partially read.
//!
//! # What this stage does not do
//!
//! The per-tick **state** digests in [`StateEnvelope`] are produced by a
//! running session (F59-B): this module compares, chains, seals and transports
//! them, and [`ReplayRecord::verdict_against`] is the one call a replay runner
//! makes when it has a run's envelope in hand. No state hash is fabricated
//! here; the synthetic fixtures digest *labelled fixture descriptions* and say
//! so in their names ([`synthetic_replay_record`]). The inspector and xtask
//! commands, the real capture path and the freshness/capability validation
//! against an actual run are F59-C and F59-D.
//!
//! Every value in this module is newly authored project design. Nothing here
//! is derived from original game data, and no record in it can award
//! `verified_original` on its own — only the evidence ledger
//! (`cs_types::evidence`) can, and only through a real observation.

