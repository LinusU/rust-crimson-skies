/// Why an encoded document was refused.
///
/// Every check happens before a value is interpreted: size, encoding, header,
/// schema, line count and checksum first, then the fields.
#[derive(Clone, Debug, PartialEq)]
pub enum DecodeError {
    /// The document is larger than [`MAX_REPLAY_BYTES`].
    TooLarge {
        /// Its measured size in bytes.
        len: usize,
    },
    /// The document is not UTF-8.
    NotUtf8,
    /// The header is not `CSREPLAY <major>.<minor>` or `CSCAPTURE <major>.<minor>`.
    BadHeader,
    /// The document's schema major is not readable by this build. The bytes
    /// are untouched: a caller must not overwrite them.
    UnsupportedMajor {
        /// The declared major.
        major: u16,
    },
    /// The document has more lines than [`MAX_REPLAY_LINES`].
    TooManyLines,
    /// The document does not end with a `checksum=` line.
    MissingChecksum,
    /// The document's checksum does not match its content.
    ChecksumMismatch,
    /// A line is not `key=value`, or its value is not what its key allows.
    Malformed {
        /// The 1-based line number, counting the header.
        line: usize,
        /// What was wrong with it.
        reason: &'static str,
    },
    /// A field the document requires is absent.
    MissingField(&'static str),
    /// A field was repeated where only one is allowed.
    RepeatedField(&'static str),
    /// The decoded record broke a record rule.
    Record(ReplayError),
    /// A recorded input tick broke the stream's ordering.
    Stream(cs_types::input::StreamError),
}

impl fmt::Display for DecodeError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::TooLarge { len } => {
                write!(
                    f,
                    "document is {len} bytes, over the bound of {MAX_REPLAY_BYTES}"
                )
            }
            Self::NotUtf8 => write!(f, "document is not UTF-8"),
            Self::BadHeader => write!(f, "document header is not `CSREPLAY <major>.<minor>`"),
            Self::UnsupportedMajor { major } => {
                write!(
                    f,
                    "document schema major {major} is not readable by this build"
                )
            }
            Self::TooManyLines => {
                write!(f, "document has more than {MAX_REPLAY_LINES} lines")
            }
            Self::MissingChecksum => write!(f, "document has no trailing checksum line"),
            Self::ChecksumMismatch => {
                write!(f, "document checksum does not match its content")
            }
            Self::Malformed { line, reason } => write!(f, "line {line}: {reason}"),
            Self::MissingField(name) => write!(f, "document lacks required field {name}"),
            Self::RepeatedField(name) => write!(f, "document repeats field {name}"),
            Self::Record(error) => write!(f, "{error}"),
            Self::Stream(error) => write!(f, "recorded input: {error}"),
        }
    }
}

impl std::error::Error for DecodeError {}

impl From<ReplayError> for DecodeError {
    fn from(error: ReplayError) -> Self {
        Self::Record(error)
    }
}

impl From<cs_types::input::StreamError> for DecodeError {
    fn from(error: cs_types::input::StreamError) -> Self {
        Self::Stream(error)
    }
}

impl From<EnvelopeError> for DecodeError {
    fn from(error: EnvelopeError) -> Self {
        Self::Record(ReplayError::Envelope(error))
    }
}

/// Looks a claim status up by its label.
///
/// [`ClaimStatus`] is F01's seven-state vocabulary and this reads its own
/// `label` table rather than restating the spellings, so a status added there
/// and not here is refused as unknown instead of silently reading as some other
/// one.
fn claim_status_from_label(label: &str) -> Option<ClaimStatus> {
    [
        ClaimStatus::Documented,
        ClaimStatus::ObservedTool,
        ClaimStatus::VerifiedOriginal,
        ClaimStatus::Inferred,
        ClaimStatus::Designed,
        ClaimStatus::Unknown,
        ClaimStatus::Contradicted,
    ]
    .into_iter()
    .find(|status| status.label() == label)
}

/// Parses a bounded decimal field.
fn parse_u64(line: usize, text: &str) -> Result<u64, DecodeError> {
    if text.is_empty() || !text.bytes().all(|b| b.is_ascii_digit()) {
        return Err(DecodeError::Malformed {
            line,
            reason: "expected a decimal number",
        });
    }
    text.parse().map_err(|_| DecodeError::Malformed {
        line,
        reason: "number out of range",
    })
}

/// Parses a bounded boolean field written as `0` or `1`.
fn parse_bool(line: usize, text: &str) -> Result<bool, DecodeError> {
    match text {
        "0" => Ok(false),
        "1" => Ok(true),
        _ => Err(DecodeError::Malformed {
            line,
            reason: "expected 0 or 1",
        }),
    }
}

fn write_bool(out: &mut String, value: bool) {
    out.push_str(if value { "1" } else { "0" });
    out.push('\n');
}

/// Opens a sealed line document: returns the body its checksum covers and the
/// version its header declares.
///
/// The body excludes the header line and the trailing `checksum=` line, and it
/// has already been verified against the stored checksum. What the body means
/// is the decoder's business.
fn sealed_body<'a>(magic: &str, bytes: &'a [u8]) -> Result<(&'a str, ReplayVersion), DecodeError> {
    if bytes.len() > MAX_REPLAY_BYTES {
        return Err(DecodeError::TooLarge { len: bytes.len() });
    }
    let text = std::str::from_utf8(bytes).map_err(|_| DecodeError::NotUtf8)?;
    let header_end = text.find('\n').ok_or(DecodeError::BadHeader)?;
    let rest = text[..header_end]
        .strip_prefix(magic)
        .and_then(|rest| rest.strip_prefix(' '))
        .ok_or(DecodeError::BadHeader)?;
    let (major, minor) = rest.split_once('.').ok_or(DecodeError::BadHeader)?;
    let number = |text: &str| -> Result<u16, DecodeError> {
        if text.is_empty() || !text.bytes().all(|b| b.is_ascii_digit()) {
            return Err(DecodeError::BadHeader);
        }
        text.parse().map_err(|_| DecodeError::BadHeader)
    };
    let schema = ReplayVersion {
        major: number(major)?,
        minor: number(minor)?,
    };
    if !schema.is_readable() {
        return Err(DecodeError::UnsupportedMajor {
            major: schema.major,
        });
    }
    let body = text
        .strip_suffix('\n')
        .ok_or(DecodeError::MissingChecksum)?;
    let checksum_start = body
        .rfind('\n')
        .map(|at| at + 1)
        .ok_or(DecodeError::MissingChecksum)?;
    let stored = body[checksum_start..]
        .strip_prefix(CHECKSUM_KEY)
        .ok_or(DecodeError::MissingChecksum)?;
    if stored.len() != 64
        || !stored
            .bytes()
            .all(|b| matches!(b, b'0'..=b'9' | b'a'..=b'f'))
    {
        return Err(DecodeError::MissingChecksum);
    }
    let expected = sha256(&bytes[..checksum_start]);
    if stored != expected.to_hex() {
        return Err(DecodeError::ChecksumMismatch);
    }
    Ok((&text[header_end + 1..checksum_start], schema))
}

fn check_line_count(body: &str) -> Result<(), DecodeError> {
    if body.lines().count() > MAX_REPLAY_LINES {
        return Err(DecodeError::TooManyLines);
    }
    Ok(())
}

/// Seals a document body: appends the `checksum=` line over everything above.
fn seal(out: &mut String) {
    let digest = sha256(out.as_bytes()).to_hex();
    out.push_str(CHECKSUM_KEY);
    out.push_str(&digest);
    out.push('\n');
}

/// Encodes one recorded input tick: `<edges>|<axes>`, comma-separated within
/// each half. A `|` is used because no action, command or number can contain
/// one, so the split is unambiguous.
fn encode_frame(frame: &InputFrame) -> String {
    let edges = frame
        .edges()
        .iter()
        .map(|edge| edge.label())
        .collect::<Vec<_>>()
        .join(",");
    let axes = frame
        .axes()
        .iter()
        .map(|axis| format!("{}={}", axis.command().label(), axis.quantized()))
        .collect::<Vec<_>>()
        .join(",");
    format!("{edges}|{axes}")
}

/// Parses one recorded input tick.
///
/// The value is `<edges>|<axes>`, comma-separated within each half, and the
/// tick comes from the key. A `|` is used because no action, command or number
/// contains one, so the split is unambiguous.
fn parse_frame(line: usize, tick: Tick, text: &str) -> Result<InputFrame, DecodeError> {
    let (edges, axes) = text.split_once('|').ok_or(DecodeError::Malformed {
        line,
        reason: "an input record is `<edges>|<axes>`",
    })?;
    let mut frame = InputFrame::new(tick);
    if !edges.is_empty() {
        for label in edges.split(',') {
            let action = Action::from_label(label).ok_or(DecodeError::Malformed {
                line,
                reason: "unknown recorded action",
            })?;
            frame.push_edge(action);
        }
    }
    if !axes.is_empty() {
        for axis in axes.split(',') {
            let (command, value) = axis.rsplit_once('=').ok_or(DecodeError::Malformed {
                line,
                reason: "an axis sample is `<command>=<quantized>`",
            })?;
            let command = FlightCommand::from_label(command).ok_or(DecodeError::Malformed {
                line,
                reason: "unknown recorded command",
            })?;
            if value.is_empty() || !value.bytes().all(|b| b.is_ascii_digit() || b == b'-') {
                return Err(DecodeError::Malformed {
                    line,
                    reason: "an axis sample must be a signed integer",
                });
            }
            let quantized = value.parse::<i16>().map_err(|_| DecodeError::Malformed {
                line,
                reason: "axis sample out of range",
            })?;
            let sample = AxisValue::from_quantized(command, quantized).map_err(|_| {
                DecodeError::Malformed {
                    line,
                    reason: "axis sample is not a continuous command",
                }
            })?;
            frame.set_axis(sample);
        }
    }
    Ok(frame)
}

fn parse_f64(line: usize, text: &str) -> Result<f64, DecodeError> {
    if text.is_empty() {
        return Err(DecodeError::Malformed {
            line,
            reason: "expected a number",
        });
    }
    text.parse::<f64>().map_err(|_| DecodeError::Malformed {
        line,
        reason: "expected a number",
    })
}

fn parse_hash(line: usize, text: &str) -> Result<ContentHash, DecodeError> {
    ContentHash::from_hex(text).map_err(|_| DecodeError::Malformed {
        line,
        reason: "expected 64 lowercase hex digits",
    })
}

/// Stores a single-valued field, refusing a second occurrence of the same key.
fn set_once<T>(slot: &mut Option<T>, value: T, name: &'static str) -> Result<(), DecodeError> {
    if slot.is_some() {
        return Err(DecodeError::RepeatedField(name));
    }
    *slot = Some(value);
    Ok(())
}

/// Encodes a validated [`ReplayRecord`] into the bounded line document.
///
/// # Errors
///
/// Every error of [`ReplayRecord::validate`]. An invalid record is refused
/// rather than encoded, so a document on disk is always a record that means
/// what it says.
pub fn encode(record: &ReplayRecord) -> Result<Vec<u8>, ReplayError> {
    record.validate()?;
    let mut out = String::new();
    out.push_str(&format!("{REPLAY_MAGIC} {}\n", record.schema));
    out.push_str(&format!("subject={}\n", record.subject.as_str()));
    out.push_str(&format!("tree={}\n", record.fingerprint.tree));
    out.push_str(&format!("engine={}\n", record.fingerprint.engine));
    out.push_str(&format!("content={}\n", record.fingerprint.content));
    out.push_str(&format!("rules={}\n", record.fingerprint.rules));
    out.push_str(&format!("toolchain={}\n", record.fingerprint.toolchain));
    out.push_str(&format!(
        "platform.os={}\n",
        record.fingerprint.platform.os()
    ));
    out.push_str(&format!(
        "platform.arch={}\n",
        record.fingerprint.platform.arch()
    ));
    out.push_str(&format!("tick_rate={}\n", record.tick_rate));
    out.push_str(&format!("first_tick={}\n", record.first_tick.0));
    out.push_str(&format!("last_tick={}\n", record.last_tick.0));
    out.push_str(&format!("initial.label={}\n", record.initial_state.label));
    out.push_str(&format!("initial.digest={}\n", record.initial_state.digest));
    out.push_str(&format!("seed.root={}\n", record.seeds.root()));
    for stream in record.seeds.streams() {
        out.push_str(&format!("seed.stream.{}={}\n", stream.label, stream.seed));
    }
    out.push_str(&format!("purpose={}\n", record.overrides.purpose()));
    out.push_str("profile_write=");
    write_bool(&mut out, record.overrides.production_profile_write());
    for entry in record.overrides.entries() {
        out.push_str(&format!("override.{}={}\n", entry.name, entry.detail));
    }
    for choice in record.choices.choices() {
        out.push_str(&format!(
            "choice.{}={}|{}|{}\n",
            choice.slot.label(),
            choice.provenance.class.label(),
            choice.provenance.claim_id,
            choice.value
        ));
    }
    for input in record.stream.records() {
        out.push_str(&format!(
            "input.{}={}\n",
            input.frame_tick().0,
            encode_frame(input)
        ));
    }
    for entry in record.promised.entries() {
        out.push_str(&format!("envelope.{}={}\n", entry.tick.0, entry.state));
    }
    for field in &record.extra {
        out.push_str(&format!("{}={}\n", field.key, field.value));
    }
    seal(&mut out);
    Ok(out.into_bytes())
}

/// Decodes and fully validates a replay document. Never panics on any input.
pub fn decode(bytes: &[u8]) -> Result<ReplayRecord, DecodeError> {
    let (body, schema) = sealed_body(REPLAY_MAGIC, bytes)?;
    check_line_count(body)?;

    let mut subject_slot = None;
    let mut tree = None;
    let mut engine = None;
    let mut content = None;
    let mut rules = None;
    let mut toolchain = None;
    let mut os = None;
    let mut arch = None;
    let mut tick_rate = None;
    let mut first_tick = None;
    let mut last_tick = None;
    let mut initial_label = None;
    let mut initial_digest = None;
    let mut seed_root = None;
    let mut seed_streams: Vec<SeedStream> = Vec::new();
    let mut purpose = None;
    let mut profile_write: Option<bool> = None;
    let mut overrides: Vec<OverrideEntry> = Vec::new();
    let mut choices: Vec<AuthoredChoice> = Vec::new();
    let mut stream = CommandStream::new();
    let mut promised = StateEnvelope::new();
    let mut extra: Vec<ReplayField> = Vec::new();

    for (index, line) in body.lines().enumerate() {
        let number = index + 2;
        let (key, value) = line.split_once('=').ok_or(DecodeError::Malformed {
            line: number,
            reason: "expected key=value",
        })?;
        match key {
            "subject" => {
                let subject = ContentId::parse(value).map_err(|_| DecodeError::Malformed {
                    line: number,
                    reason: "invalid content id",
                })?;
                set_once(&mut subject_slot, subject, "subject")?;
            }
            "tree" => {
                set_once(&mut tree, BuildId::new(value)?, "tree")?;
            }
            "engine" => {
                set_once(&mut engine, parse_hash(number, value)?, "engine")?;
            }
            "content" => {
                set_once(&mut content, parse_hash(number, value)?, "content")?;
            }
            "rules" => {
                set_once(&mut rules, parse_hash(number, value)?, "rules")?;
            }
            "toolchain" => {
                set_once(&mut toolchain, value.to_owned(), "toolchain")?;
            }
            "platform.os" => {
                set_once(&mut os, value.to_owned(), "platform.os")?;
            }
            "platform.arch" => {
                set_once(&mut arch, value.to_owned(), "platform.arch")?;
            }
            "tick_rate" => {
                let rate = u32::try_from(parse_u64(number, value)?).map_err(|_| {
                    DecodeError::Malformed {
                        line: number,
                        reason: "tick rate out of range",
                    }
                })?;
                set_once(&mut tick_rate, rate, "tick_rate")?;
            }
            "first_tick" => {
                set_once(
                    &mut first_tick,
                    Tick(parse_u64(number, value)?),
                    "first_tick",
                )?;
            }
            "last_tick" => {
                set_once(&mut last_tick, Tick(parse_u64(number, value)?), "last_tick")?;
            }
            "initial.label" => {
                set_once(&mut initial_label, value.to_owned(), "initial.label")?;
            }
            "initial.digest" => {
                set_once(
                    &mut initial_digest,
                    parse_hash(number, value)?,
                    "initial.digest",
                )?;
            }
            "seed.root" => {
                set_once(&mut seed_root, parse_u64(number, value)?, "seed.root")?;
            }
            "purpose" => {
                let parsed = RunPurpose::from_label(value).ok_or(DecodeError::Malformed {
                    line: number,
                    reason: "unknown run purpose",
                })?;
                set_once(&mut purpose, parsed, "purpose")?;
            }
            "profile_write" => {
                set_once(
                    &mut profile_write,
                    parse_bool(number, value)?,
                    "profile_write",
                )?;
            }
            _ => {
                if let Some(label) = key.strip_prefix("seed.stream.") {
                    seed_streams.push(SeedStream {
                        label: label.to_owned(),
                        seed: parse_u64(number, value)?,
                    });
                } else if let Some(name) = key.strip_prefix("override.") {
                    overrides.push(OverrideEntry {
                        name: name.to_owned(),
                        detail: value.to_owned(),
                    });
                } else if let Some(slot) = key.strip_prefix("choice.") {
                    let mut parts = value.splitn(3, '|');
                    let class = parts.next().unwrap_or_default();
                    let claim = parts.next().unwrap_or_default();
                    let text = parts.next().ok_or(DecodeError::Malformed {
                        line: number,
                        reason: "a choice is `<class>|<claim>|<value>`",
                    })?;
                    let class = claim_status_from_label(class).ok_or(DecodeError::Malformed {
                        line: number,
                        reason: "unknown claim status",
                    })?;
                    let claim = ClaimId::new(claim).map_err(|_| DecodeError::Malformed {
                        line: number,
                        reason: "invalid claim id",
                    })?;
                    choices.push(AuthoredChoice {
                        slot: ChoiceSlot::from_label(slot).ok_or(DecodeError::Malformed {
                            line: number,
                            reason: "unknown choice slot",
                        })?,
                        value: text.to_owned(),
                        provenance: Provenance {
                            claim_id: claim,
                            class,
                            source: None,
                        },
                    });
                } else if let Some(tick) = key.strip_prefix("input.") {
                    let tick = Tick(parse_u64(number, tick)?);
                    let frame = parse_frame(number, tick, value)?;
                    stream.record_tick(frame)?;
                } else if let Some(tick) = key.strip_prefix("envelope.") {
                    let tick = Tick(parse_u64(number, tick)?);
                    promised.push(tick, parse_hash(number, value)?)?;
                } else {
                    extra.push(ReplayField {
                        key: key.to_owned(),
                        value: value.to_owned(),
                    });
                }
            }
        }
    }

    let record = ReplayRecord {
        schema,
        subject: subject_slot.ok_or(DecodeError::MissingField("subject"))?,
        fingerprint: BuildFingerprint {
            tree: tree.ok_or(DecodeError::MissingField("tree"))?,
            engine: engine.ok_or(DecodeError::MissingField("engine"))?,
            content: content.ok_or(DecodeError::MissingField("content"))?,
            rules: rules.ok_or(DecodeError::MissingField("rules"))?,
            toolchain: toolchain.ok_or(DecodeError::MissingField("toolchain"))?,
            platform: PlatformTag::new(
                &os.ok_or(DecodeError::MissingField("platform.os"))?,
                &arch.ok_or(DecodeError::MissingField("platform.arch"))?,
            )?,
        },
        initial_state: InitialState::new(
            &initial_label.ok_or(DecodeError::MissingField("initial.label"))?,
            initial_digest.ok_or(DecodeError::MissingField("initial.digest"))?,
        )?,
        stream,
        seeds: ReplaySeeds::new(
            seed_root.ok_or(DecodeError::MissingField("seed.root"))?,
            seed_streams,
        )?,
        tick_rate: tick_rate.ok_or(DecodeError::MissingField("tick_rate"))?,
        first_tick: first_tick.ok_or(DecodeError::MissingField("first_tick"))?,
        last_tick: last_tick.ok_or(DecodeError::MissingField("last_tick"))?,
        choices: AuthoredChoices::new(choices)?,
        promised,
        overrides: OverrideLog::new(
            purpose.unwrap_or_default(),
            overrides,
            profile_write.unwrap_or(false),
        )?,
        extra,
    };
    record.validate()?;
    Ok(record)
}

/// Encodes a validated [`CaptureRecord`] into the bounded line document.
///
/// # Errors
///
/// Every error of [`CaptureRecord::validate`].
pub fn encode_capture(record: &CaptureRecord) -> Result<Vec<u8>, CaptureError> {
    record.validate()?;
    let mut out = String::new();
    out.push_str(&format!("{CAPTURE_MAGIC} {}\n", ReplayVersion::CURRENT));
    out.push_str(&format!("media={}\n", record.media));
    if let ArtifactMedia::PcmCapture(role) = record.media {
        out.push_str(&format!("pcm.role={}\n", pcm_role_label(role)));
    }
    out.push_str(&format!("origin={}\n", record.origin));
    out.push_str(&format!("capture_tick={}\n", record.capture_tick.0));
    out.push_str(&format!("camera.mode={}\n", record.camera.mode));
    let eye = record.camera.eye.to_array();
    out.push_str(&format!("camera.eye={},{},{}\n", eye[0], eye[1], eye[2]));
    let orientation = record.camera.orientation.components();
    out.push_str(&format!(
        "camera.orientation={},{},{},{}\n",
        orientation[0], orientation[1], orientation[2], orientation[3]
    ));
    out.push_str(&format!(
        "camera.fov_rad={}\n",
        record.camera.vertical_fov.0
    ));
    out.push_str(&format!("render.width={}\n", record.render.width));
    out.push_str(&format!("render.height={}\n", record.render.height));
    out.push_str(&format!(
        "render.exposure_milli={}\n",
        record.render.exposure_milli
    ));
    out.push_str(&format!(
        "render.gamma_milli={}\n",
        record.render.gamma_milli
    ));
    out.push_str(&format!("render.tonemap={}\n", record.render.tonemap));
    out.push_str(&format!(
        "render.msaa_samples={}\n",
        record.render.msaa_samples
    ));
    out.push_str("render.shadows=");
    write_bool(&mut out, record.render.shadows);
    out.push_str(&format!("build={}\n", record.build));
    out.push_str(&format!("replay_signature={}\n", record.replay_signature));
    out.push_str(&format!("artifact={}\n", record.artifact));
    out.push_str(&format!("bytes={}\n", record.bytes));
    seal(&mut out);
    Ok(out.into_bytes())
}

/// Decodes and fully validates a capture document. Never panics on any input.
pub fn decode_capture(bytes: &[u8]) -> Result<CaptureRecord, DecodeError> {
    let (body, _schema) = sealed_body(CAPTURE_MAGIC, bytes)?;
    check_line_count(body)?;

    let mut media = None;
    let mut pcm_role = None;
    let mut origin = None;
    let mut capture_tick = None;
    let mut mode = None;
    let mut eye: Option<WorldPosition> = None;
    let mut orientation: Option<Quaternion> = None;
    let mut fov: Option<Radians> = None;
    let mut width = None;
    let mut height = None;
    let mut exposure = None;
    let mut gamma = None;
    let mut tonemap = None;
    let mut msaa = None;
    let mut shadows = None;
    let mut build = None;
    let mut replay_signature = None;
    let mut artifact = None;
    let mut bytes_len = None;

    for (index, line) in body.lines().enumerate() {
        let number = index + 2;
        let (key, value) = line.split_once('=').ok_or(DecodeError::Malformed {
            line: number,
            reason: "expected key=value",
        })?;
        let number_field = |text: &str| -> Result<u32, DecodeError> {
            u32::try_from(parse_u64(number, text)?).map_err(|_| DecodeError::Malformed {
                line: number,
                reason: "number out of range",
            })
        };
        match key {
            "media" => {
                let parsed = match value {
                    "trace" => ArtifactMedia::Trace,
                    "screenshot" => ArtifactMedia::Screenshot,
                    "pcm_capture" => ArtifactMedia::PcmCapture(PcmRole::DecodeOnly),
                    "report" => ArtifactMedia::Report,
                    _ => {
                        return Err(DecodeError::Malformed {
                            line: number,
                            reason: "unknown capture media",
                        });
                    }
                };
                set_once(&mut media, parsed, "media")?;
            }
            "pcm.role" => {
                let parsed = pcm_role_from_label(value).ok_or(DecodeError::Malformed {
                    line: number,
                    reason: "unknown pcm role",
                })?;
                set_once(&mut pcm_role, parsed, "pcm.role")?;
            }
            "origin" => {
                let parsed = ArtifactOrigin::from_label(value).ok_or(DecodeError::Malformed {
                    line: number,
                    reason: "unknown capture origin",
                })?;
                set_once(&mut origin, parsed, "origin")?;
            }
            "capture_tick" => {
                set_once(
                    &mut capture_tick,
                    Tick(parse_u64(number, value)?),
                    "capture_tick",
                )?;
            }
            "camera.mode" => {
                let parsed = camera_mode_from_label(value).ok_or(DecodeError::Malformed {
                    line: number,
                    reason: "unknown camera mode",
                })?;
                set_once(&mut mode, parsed, "camera.mode")?;
            }
            "camera.eye" => {
                let position = parse_f64_triple(number, value)?;
                let parsed =
                    WorldPosition::try_new(position).map_err(|_| DecodeError::Malformed {
                        line: number,
                        reason: "invalid camera position",
                    })?;
                set_once(&mut eye, parsed, "camera.eye")?;
            }
            "camera.orientation" => {
                let components = parse_f64_quad(number, value)?;
                let parsed =
                    Quaternion::try_new(components).map_err(|_| DecodeError::Malformed {
                        line: number,
                        reason: "invalid camera orientation",
                    })?;
                set_once(&mut orientation, parsed, "camera.orientation")?;
            }
            "camera.fov_rad" => {
                set_once(
                    &mut fov,
                    Radians(parse_f64(number, value)?),
                    "camera.fov_rad",
                )?;
            }
            "render.width" => set_once(&mut width, number_field(value)?, "render.width")?,
            "render.height" => set_once(&mut height, number_field(value)?, "render.height")?,
            "render.exposure_milli" => {
                set_once(&mut exposure, number_field(value)?, "render.exposure_milli")?;
            }
            "render.gamma_milli" => {
                set_once(&mut gamma, number_field(value)?, "render.gamma_milli")?;
            }
            "render.tonemap" => {
                let parsed = TonemapKind::from_label(value).ok_or(DecodeError::Malformed {
                    line: number,
                    reason: "unknown tonemap",
                })?;
                set_once(&mut tonemap, parsed, "render.tonemap")?;
            }
            "render.msaa_samples" => {
                set_once(&mut msaa, number_field(value)?, "render.msaa_samples")?;
            }
            "render.shadows" => {
                set_once(&mut shadows, parse_bool(number, value)?, "render.shadows")?;
            }
            "build" => set_once(&mut build, BuildId::new(value)?, "build")?,
            "replay_signature" => {
                set_once(
                    &mut replay_signature,
                    parse_hash(number, value)?,
                    "replay_signature",
                )?;
            }
            "artifact" => {
                set_once(&mut artifact, parse_hash(number, value)?, "artifact")?;
            }
            "bytes" => {
                set_once(&mut bytes_len, parse_u64(number, value)?, "bytes")?;
            }
            _ => {
                return Err(DecodeError::Malformed {
                    line: number,
                    reason: "unknown capture field",
                });
            }
        }
    }

    let media = match (media.ok_or(DecodeError::MissingField("media"))?, pcm_role) {
        // A pcm_capture always states its role: the difference between a decode
        // artifact and audible playback review is the whole capability claim
        // (contract "Evidence record minimum"), so a document may not leave it
        // to be inferred.
        (ArtifactMedia::PcmCapture(_), None) => {
            return Err(DecodeError::MissingField("pcm.role"));
        }
        (ArtifactMedia::PcmCapture(_), Some(role)) => ArtifactMedia::PcmCapture(role),
        (_, Some(_)) => {
            return Err(DecodeError::Malformed {
                line: 2,
                reason: "pcm.role is only valid for a pcm_capture",
            });
        }
        (other, None) => other,
    };
    let eye = eye.ok_or(DecodeError::MissingField("camera.eye"))?;
    let orientation = orientation.ok_or(DecodeError::MissingField("camera.orientation"))?;
    let record = CaptureRecord {
        media,
        origin: origin.ok_or(DecodeError::MissingField("origin"))?,
        capture_tick: capture_tick.ok_or(DecodeError::MissingField("capture_tick"))?,
        camera: CaptureCamera {
            mode: mode.ok_or(DecodeError::MissingField("camera.mode"))?,
            eye,
            orientation,
            vertical_fov: fov.ok_or(DecodeError::MissingField("camera.fov_rad"))?,
        },
        render: RenderConfig {
            width: width.ok_or(DecodeError::MissingField("render.width"))?,
            height: height.ok_or(DecodeError::MissingField("render.height"))?,
            exposure_milli: exposure.ok_or(DecodeError::MissingField("render.exposure_milli"))?,
            gamma_milli: gamma.ok_or(DecodeError::MissingField("render.gamma_milli"))?,
            tonemap: tonemap.ok_or(DecodeError::MissingField("render.tonemap"))?,
            msaa_samples: msaa.ok_or(DecodeError::MissingField("render.msaa_samples"))?,
            shadows: shadows.ok_or(DecodeError::MissingField("render.shadows"))?,
        },
        build: build.ok_or(DecodeError::MissingField("build"))?,
        replay_signature: replay_signature.ok_or(DecodeError::MissingField("replay_signature"))?,
        artifact: artifact.ok_or(DecodeError::MissingField("artifact"))?,
        bytes: bytes_len.ok_or(DecodeError::MissingField("bytes"))?,
    };
    record
        .validate()
        .map_err(|error| DecodeError::Record(ReplayError::Camera(error)))?;
    Ok(record)
}

fn parse_f64_triple(line: usize, text: &str) -> Result<[f64; 3], DecodeError> {
    let parts: Vec<&str> = text.split(',').collect();
    if parts.len() != 3 {
        return Err(DecodeError::Malformed {
            line,
            reason: "expected three comma-separated numbers",
        });
    }
    let mut values = [0.0; 3];
    for (slot, part) in values.iter_mut().zip(parts) {
        *slot = parse_f64(line, part)?;
    }
    Ok(values)
}

fn parse_f64_quad(line: usize, text: &str) -> Result<[f64; 4], DecodeError> {
    let parts: Vec<&str> = text.split(',').collect();
    if parts.len() != 4 {
        return Err(DecodeError::Malformed {
            line,
            reason: "expected four comma-separated numbers",
        });
    }
    let mut values = [0.0; 4];
    for (slot, part) in values.iter_mut().zip(parts) {
        *slot = parse_f64(line, part)?;
    }
    Ok(values)
}

