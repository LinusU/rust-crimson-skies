/// A SHA-256 digest of a [`CommandStream`].
///
/// The stream itself is already a deterministic, quantized record
/// (`cs_types::input::CommandStream`); this digest is what a signature, a
/// report or a difference list can name without embedding a dump of it. The
/// encoding is length-prefixed per field and domain-separated, so a record
/// whose ticks, edges or axis samples moved cannot collide with the original
/// by reordering its fields.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub struct InputStreamDigest(ContentHash);

impl InputStreamDigest {
    /// Digests a recorded command stream.
    #[must_use]
    pub fn of(stream: &CommandStream) -> Self {
        let mut hasher = Sha256::new();
        hasher.update(INPUT_STREAM_DOMAIN);
        put_u64(&mut hasher, stream.len() as u64);
        for record in stream.records() {
            put_u64(&mut hasher, record.frame_tick().0);
            put_u64(&mut hasher, record.edges().len() as u64);
            for edge in record.edges() {
                put_text(&mut hasher, edge.label());
            }
            put_u64(&mut hasher, record.axes().len() as u64);
            for axis in record.axes() {
                put_text(&mut hasher, axis.command().label());
                put_u64(&mut hasher, i64::from(axis.quantized()) as u64);
            }
        }
        Self(hasher.finalize())
    }

    /// The digest bytes.
    pub const fn digest(self) -> ContentHash {
        self.0
    }
}

impl fmt::Display for InputStreamDigest {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}", self.0)
    }
}

