/// The capability classes of `docs/contracts/CLI-EVIDENCE.md`. They are
/// non-interchangeable: a machine with `retail` access has no `gpu` because
/// it read the owner's files, and a loopback run is `network_local` whatever
/// else it can do.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum CapabilityClass {
    /// Newly authored synthetic fixtures, no original data.
    Synthetic,
    /// Read access to the owner's original installation.
    Retail,
    /// A real GPU render, possibly offscreen.
    Gpu,
    /// A real audio device.
    Audio,
    /// Networking on one machine or a loopback.
    NetworkLocal,
    /// Networking between real provisioned hosts.
    NetworkReal,
    /// The owner playing the game.
    HumanPlay,
    /// The owner looking or listening at something.
    HumanReview,
}

impl CapabilityClass {
    /// Every class, in a stable order.
    pub const ALL: &'static [CapabilityClass] = &[
        Self::Synthetic,
        Self::Retail,
        Self::Gpu,
        Self::Audio,
        Self::NetworkLocal,
        Self::NetworkReal,
        Self::HumanPlay,
        Self::HumanReview,
    ];

    /// The stable label, which is also the `$CS_CAPABILITIES` spelling.
    pub const fn label(self) -> &'static str {
        match self {
            Self::Synthetic => "synthetic",
            Self::Retail => "retail",
            Self::Gpu => "gpu",
            Self::Audio => "audio",
            Self::NetworkLocal => "network_local",
            Self::NetworkReal => "network_real",
            Self::HumanPlay => "human_play",
            Self::HumanReview => "human_review",
        }
    }

    /// Looks a class up by its label; `None` for an unknown capability.
    pub fn from_label(label: &str) -> Option<Self> {
        Self::ALL
            .iter()
            .copied()
            .find(|class| class.label() == label)
    }
}

impl fmt::Display for CapabilityClass {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.label())
    }
}

/// What a machine says it can really do.
///
/// The set is a declaration, not a measurement: it is parsed from
/// `$CS_CAPABILITIES` and treated as exactly that. Every check in this module
/// is a *subtract* from this set — nothing here can widen it — which is why a
/// headless machine can never report a visual or audible verification.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct DeclaredCapabilities {
    classes: BTreeSet<CapabilityClass>,
}

impl DeclaredCapabilities {
    /// An empty declaration: nothing is available.
    #[must_use]
    pub fn none() -> Self {
        Self::default()
    }

    /// The declaration a headless synthetic build machine makes: synthetic
    /// fixtures only.
    #[must_use]
    pub fn headless_synthetic() -> Self {
        Self::of([CapabilityClass::Synthetic])
    }

    /// Builds a declaration from a set of classes, in canonical order.
    #[must_use]
    pub fn of(classes: impl IntoIterator<Item = CapabilityClass>) -> Self {
        Self {
            classes: classes.into_iter().collect(),
        }
    }

    /// Parses the comma-separated `$CS_CAPABILITIES` spelling.
    ///
    /// An empty or whitespace-only list is an empty declaration, which is what
    /// an unset variable means. A blank element or an unknown name is an error
    /// rather than a silent omission: a typo in a capability list must not
    /// quietly remove a capability the owner granted.
    ///
    /// # Errors
    ///
    /// [`ReplayError::Blank`] for an empty element and [`ReplayError::Syntax`]
    /// for an unknown capability name.
    pub fn parse(list: &str) -> Result<Self, ReplayError> {
        if list.trim().is_empty() {
            return Ok(Self::none());
        }
        let mut classes = BTreeSet::new();
        for element in list.split(',') {
            let element = element.trim();
            if element.is_empty() {
                return Err(ReplayError::Blank {
                    field: "capability list element",
                });
            }
            let class = CapabilityClass::from_label(element).ok_or(ReplayError::Syntax {
                field: "capability list element",
                reason: "unknown capability class",
            })?;
            classes.insert(class);
        }
        Ok(Self { classes })
    }

    /// The declared classes, in canonical order.
    pub fn classes(&self) -> impl Iterator<Item = CapabilityClass> + '_ {
        self.classes.iter().copied()
    }

    /// Whether the machine declares `class`.
    pub fn contains(&self, class: CapabilityClass) -> bool {
        self.classes.contains(&class)
    }

    /// Every required class the machine does **not** declare, in canonical
    /// order.
    #[must_use]
    pub fn missing(&self, required: &[CapabilityClass]) -> Vec<CapabilityClass> {
        required
            .iter()
            .copied()
            .filter(|class| !self.classes.contains(class))
            .collect()
    }

    /// Whether the machine provides neither a GPU nor an audio device: the
    /// headless case of AC04.
    pub fn is_headless(&self) -> bool {
        !self.classes.contains(&CapabilityClass::Gpu)
            && !self.classes.contains(&CapabilityClass::Audio)
    }

    /// The canonical comma-separated spelling.
    #[must_use]
    pub fn label(&self) -> String {
        self.classes
            .iter()
            .map(|class| class.label())
            .collect::<Vec<_>>()
            .join(",")
    }
}

impl fmt::Display for DeclaredCapabilities {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        if self.classes.is_empty() {
            return f.write_str("<none>");
        }
        f.write_str(&self.label())
    }
}

