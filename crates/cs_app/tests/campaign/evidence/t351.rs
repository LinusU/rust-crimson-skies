//!    python3 tools/validate_evidence.py private/evidence/T351/acceptance.json \
//!      --artifact-root private/evidence/T351
//!    ```
//!    (no `--require-pass`: the nine recorded unknowns must stay recorded.)
//! 4. Commit a copy of `acceptance.json` as `docs/findings/evidence/T351.json`.

