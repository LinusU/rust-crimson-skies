//!    cargo build -p cs_inspect --locked
//!    ```
//!    (the production `cs-inspect` binary the harness runs the artifact
//!    commands with; it fails loudly if the binary is missing)
//! 1. ```sh
//!    cargo test --workspace --locked -- accept_t351_ --include-ignored \
//!      2>&1 | tee private/evidence/T351/cargo-test.log
//!    ```
//!    (record the pipeline's exit status — it is `CS_EVIDENCE_EXIT_CODE`.)
//! 2. ```sh
//!    CS_EVIDENCE_DIR=private/evidence/T351 \
//!    CS_CANDIDATE_TREE=$(git rev-parse 'HEAD^{tree}') \
//!    CS_EVIDENCE_ARGV="cargo test --workspace --locked -- accept_t351_ --include-ignored" \
//!    CS_EVIDENCE_EXIT_CODE=<status from step 1> \
