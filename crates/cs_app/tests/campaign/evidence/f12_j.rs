/// Evidence-report harness for task F12-J (Rally #376), reissued under #1174.
/// It refuses every missing input: a report written from a partial sequence
/// would be worse than no report at all.
#[test]
#[ignore = "evidence harness: needs CS_EVIDENCE_DIR, CS_CANDIDATE_TREE, CS_EVIDENCE_ARGV, CS_EVIDENCE_EXIT_CODE, CS_GAME_DIR"]
fn evidence_report_f12_j_writes_the_acceptance_report() {
    let evidence_dir = workspace_path(&env_var("CS_EVIDENCE_DIR"));
    fs::create_dir_all(&evidence_dir)
        .unwrap_or_else(|error| panic!("create {}: {error}", evidence_dir.display()));
    let candidate_tree = env_var("CS_CANDIDATE_TREE");
    let argv: Vec<String> = env_var("CS_EVIDENCE_ARGV")
        .split_whitespace()
        .map(str::to_owned)
        .collect();
    assert!(
        argv.iter().any(|arg| arg == "accept_f12_j_"),
        "CS_EVIDENCE_ARGV must be F12-J's own acceptance selection, got {argv:?}"
    );
    let exit_code: i32 = env_var("CS_EVIDENCE_EXIT_CODE")
        .parse()
        .expect("CS_EVIDENCE_EXIT_CODE must be the exit status of the acceptance run");
    let game_dir = PathBuf::from(env_var("CS_GAME_DIR"));

    let head_tree = git(&["rev-parse", "HEAD^{tree}"]);
    assert_eq!(
        candidate_tree, head_tree,
        "CS_CANDIDATE_TREE must be `git rev-parse 'HEAD^{{tree}}'` of the tested commit; \
         old reports cannot be reused for new code"
    );

    let log_path = evidence_dir.join("cargo-test.log");
    let log = fs::read_to_string(&log_path).unwrap_or_else(|error| {
        panic!(
            "cannot read the acceptance log {}: {error} (step 1 must tee its output there)",
            log_path.display()
        )
    });
    let suite = parse_f12_j_suite(&log);
    assert_eq!(
        suite.assertions.len(),
        ASSERTIONS.len(),
        "the log holds {} accept_f12_j_ tests and the report records {}: {:?}",
        suite.assertions.len(),
        ASSERTIONS.len(),
        suite.assertions
    );

    let found = discover(&game_dir)
        .expect("production discovery must read the original installation for the evidence record");
    let install_sha256 = fingerprint(&found.manifest).to_hex();
    let content_sha256 = content_fingerprint(&found.manifest).to_hex();

    // The inventory report: the production `cs-inspect inventory` command's
    // own bytes.
    let inventory_path = evidence_dir.join("inventory.json");
    let inventory_out = inventory_path.display().to_string();
    let cs_path = game_dir.display().to_string();
    run_cs_inspect(
        &cs_inspect_binary(),
        &[
            "inventory",
            "--cs-path",
            cs_path.as_str(),
            "--out",
            inventory_out.as_str(),
        ],
        &inventory_path,
        "inventory",
    );

    // The two member reads: the production `cs-inspect rof --member` reports.
    run_rof_read(
        &game_dir,
        "ASSETS/LAYOUT.CSV",
        &evidence_dir.join("rof-read-layout.json"),
    );
    run_rof_read(
        &game_dir,
        "ASSETS/SCRIPTS/SCRAPBOOKZOOM.SCRIPT",
        &evidence_dir.join("rof-read-scrapbookzoom.json"),
    );

    let artifacts = vec![
        artifact(&log_path, "log", &evidence_dir),
        artifact(&evidence_dir.join("inventory.json"), "json", &evidence_dir),
        artifact(
            &evidence_dir.join("rof-read-layout.json"),
            "json",
            &evidence_dir,
        ),
        artifact(
            &evidence_dir.join("rof-read-scrapbookzoom.json"),
            "json",
            &evidence_dir,
        ),
    ];

    let engine = Engine {
        rust: rustc_version(),
        bevy: locked_version("bevy"),
        avian: locked_version("avian3d"),
    };
    let unknowns: Vec<String> = UNKNOWNS
        .iter()
        .map(|unknown| (*unknown).to_owned())
        .collect();

    let method = format!("{ORIGINAL_METHOD} {REGENERATION}");
    let report = format!(
        "{{\n\
         \x20\"schema_version\": 1,\n\
         \x20\"task_id\": \"F12-J\",\n\
         \x20\"candidate_tree\": {},\n\
         \x20\"engine\": {},\n\
         \x20\"created_at\": {},\n\
         \x20\"command\": {{\"argv\": {}, \"cwd\": {}, \"exit_code\": {}}},\n\
         \x20\"source\": {{\"install_sha256\": {}, \"content_sha256\": {}}},\n\
         \x20\"seed\": 0,\n\
         \x20\"ticks\": {{\"start\": 0, \"end\": 0}},\n\
         \x20\"overrides\": [],\n\
         \x20\"capabilities\": [\"retail\", \"synthetic\"],\n\
         \x20\"tests\": {{\"discovered\": {}, \"executed\": {}, \"passed\": {}, \"failed\": {}, \"ignored\": {}}},\n\
         \x20\"assertions\": [{}],\n\
         \x20\"artifacts\": [{}],\n\
         \x20\"unknowns\": {},\n\
         \x20\"review\": {{\"identity\": {}, \"method\": {}}},\n\
         \x20\"claim\": \"implemented\"\n\
         }}\n",
        jstr(&candidate_tree),
        engine_json(&engine),
        jstr(&iso_utc_now()),
        str_array(&argv),
        jstr(&git(&["rev-parse", "--show-toplevel"])),
        exit_code,
        jstr(&install_sha256),
        jstr(&content_sha256),
        suite.discovered,
        suite.executed,
        suite.passed,
        suite.failed,
        suite.ignored,
        tabled_assertions(&log, ASSERTIONS),
        artifact_array(&artifacts),
        str_array(&unknowns),
        jstr(&review_identity()),
        jstr(&method),
    );

    let out = evidence_dir.join("acceptance.json");
    fs::write(&out, &report).unwrap_or_else(|error| panic!("write {}: {error}", out.display()));

    let written = fs::read_to_string(&out).expect("the report reads back");
    let content_line = format!("\"content_sha256\": \"{content_sha256}\"");
    for needle in [
        "\"schema_version\": 1",
        "\"task_id\": \"F12-J\"",
        "\"claim\": \"implemented\"",
        content_line.as_str(),
        "\"unknowns\": [",
        "\"artifacts\": [",
    ] {
        assert!(
            written.contains(needle),
            "the written report is missing {needle:?}:\n{written}"
        );
    }
    assert!(
        suite.failed == 0 && exit_code == 0,
        "the acceptance run failed (exit {exit_code}, {} failed): the report was written \
         honestly and must NOT validate; fix the tests first",
        suite.failed
    );
    println!("wrote {}", out.display());
}

/// [`parse_suite_prefixed`] with F12-J's own test prefix.
fn parse_f12_j_suite(log: &str) -> Suite {
    parse_suite_prefixed(log, "accept_f12_j_")
}

/// One `cs-inspect rof --member` run: the production command's own bytes,
/// one process per report, so the digest is what a standalone run writes.
fn run_rof_read(game_dir: &Path, member: &str, out: &Path) {
    let cs_path = game_dir.display().to_string();
    let out_path = out.display().to_string();
    let args = [
        "rof",
        "--cs-path",
        cs_path.as_str(),
        "--container",
        CRIMSON_ROF,
        "--member",
        member,
        "--out",
        out_path.as_str(),
    ];
    run_cs_inspect(
        &cs_inspect_binary(),
        &args,
        out,
        &format!("rof --member {member}"),
    );
}
