//!    cargo test --workspace --locked -- accept_f12_j_ --include-ignored \
//!      2>&1 | tee private/evidence/F12-J/cargo-test.log
//!    ```
//!    (record the pipeline's exit status — it is `CS_EVIDENCE_EXIT_CODE`.)
//! 2. ```sh
//!    CS_EVIDENCE_DIR=private/evidence/F12-J \
//!    CS_CANDIDATE_TREE=$(git rev-parse 'HEAD^{tree}') \
//!    CS_EVIDENCE_ARGV="cargo test --workspace --locked -- accept_f12_j_ --include-ignored" \
//!    CS_EVIDENCE_EXIT_CODE=<status from step 1> \
//!      cargo test --locked --test campaign evidence_report_f12_j -- --ignored
//!    ```
//! 3. ```sh
//!    python3 tools/validate_evidence.py private/evidence/F12-J/acceptance.json \
//!      --artifact-root private/evidence/F12-J
//!    ```
//!    (no `--require-pass`: the recorded unknown above must stay recorded.)
//! 4. Commit a copy of `acceptance.json` as `docs/findings/evidence/F12-J.json`.

