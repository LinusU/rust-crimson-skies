fn u32_at(bytes: &[u8], va: u64) -> u32 {
    u32::from_le_bytes(bytes_at(bytes, va, 4).try_into().expect("four bytes"))
}

fn f32_at(bytes: &[u8], va: u64) -> f32 {
    f32::from_le_bytes(bytes_at(bytes, va, 4).try_into().expect("four bytes"))
}

