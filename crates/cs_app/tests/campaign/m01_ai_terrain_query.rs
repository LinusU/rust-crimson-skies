#[test]
#[ignore = "requires CS_ENGINE_IMAGE"]
fn accept_m01_ai_terrain_query_windows_match_the_decode() {
    let image = load_engine_image().expect("CS_ENGINE_IMAGE names the measured image");
    for (va, expected, what) in WINDOWS {
        assert_eq!(
            bytes_at(&image.bytes, *va, expected.len()),
            *expected,
            "{va:#x}: {what}"
        );
    }
}

/// The ten-entry dispatch of `0x4c9a00` on `[obj+0x34] - 1`, and the float
/// constants the walk compares with.
#[test]
#[ignore = "requires CS_ENGINE_IMAGE"]
fn accept_m01_ai_terrain_query_object_dispatch_and_constants() {
    let image = load_engine_image().expect("CS_ENGINE_IMAGE names the measured image");
    let bytes = &image.bytes;

    let table: Vec<u32> = (0..10).map(|i| u32_at(bytes, 0x4c9de0 + 4 * i)).collect();
    assert_eq!(
        table,
        [
            0x4c9d89, 0x4c9daf, 0x4c9daf, 0x4c9daf, 0x4c9adf, 0x4c9c72, 0x4c9d12, 0x4c9d76,
            0x4c9d9c, 0x4c9dd7
        ],
        "types 1..=10; 2, 3 and 4 share the unknown-type error at 0x4c9daf"
    );

    assert_eq!(f32_at(bytes, 0x6032c8), 0.0, "zero-delta test");
    assert_eq!(
        f32_at(bytes, 0x6032dc),
        1.0,
        "segment parameter end / 1/delta numerator"
    );
    assert_eq!(f32_at(bytes, 0x603644), 4.5, "the caller's velocity scale");
}
